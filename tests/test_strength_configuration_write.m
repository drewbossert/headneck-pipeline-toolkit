        "ScaleFactor", [], ...
        "UnitNote", "", ...
        "AppliesForceAction", "preserve", ...
        "ReferenceAppliesForce", true, ...
        "TargetAppliesForce", true);
end


function entry = localSetEntry( ...
        name, ...
        objectType, ...
        category, ...
        group, ...
        capacityParameter, ...
        referenceValue, ...
        scaleFactor)

    entry = ...
        localEntry();

    entry.Name = ...
        name;

    entry.ObjectType = ...
        objectType;

    entry.Category = ...
        category;

    entry.Group = ...
        group;

    entry.CapacityParameter = ...
        capacityParameter;

    entry.CapacityAction = ...
        "set";

    entry.ReferenceValue = ...
        referenceValue;

    entry.TargetValue = ...
        referenceValue * ...
        scaleFactor;

    entry.ScaleFactor = ...
        scaleFactor;

    entry.UnitNote = ...
        "synthetic";
end


function localWriteConfig(filePath, config)

    try
        jsonText = ...
            jsonencode( ...
                config, ...
                "PrettyPrint", ...
                true);
    catch
        jsonText = ...
            jsonencode(config);
    end

    fid = ...
        fopen(filePath, "w");

    assert(fid >= 0, ...
        "StrengthConfigWriteTest:FileCreateFailed", ...
        "Could not create synthetic JSON:\n%s", ...
        filePath);

    cleaner = ...
        onCleanup(@() fclose(fid)); %#ok<NASGU>

    fwrite(fid, jsonText, "char");
end


function localVerifyCoordinate( ...
        testCase, ...
        config, ...
        musclePercent, ...
        actuatorPercent)

    entries = ...
        config.Entries(:);

    for iEntry = 1:numel(entries)

        if lower(string(entries(iEntry).CapacityAction)) ~= "set"
            continue;
        end

        objectType = ...
            lower(string(entries(iEntry).ObjectType));

        if endsWith(objectType, "muscle")
            expectedScale = musclePercent / 100;
        elseif contains(objectType, "actuator")
            expectedScale = actuatorPercent / 100;
        else
            continue;
        end

        verifyEqual(testCase, ...
            double(entries(iEntry).ScaleFactor), ...
            expectedScale, ...
            "AbsTol", ...
            1e-12);

        verifyEqual(testCase, ...
            double(entries(iEntry).TargetValue), ...
            double(entries(iEntry).ReferenceValue) * ...
                expectedScale, ...
            "AbsTol", ...
            1e-12);
    end
end


function localRemoveTree(root)

    if isfolder(root)
        rmdir(root, "s");
    end
end
