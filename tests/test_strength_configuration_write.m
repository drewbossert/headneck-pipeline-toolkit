function tests = test_strength_configuration_write
%TEST_STRENGTH_CONFIGURATION_WRITE Tests adaptive strength JSON generation.

    tests = functiontests(localfunctions);
end


function testWritesCanonicalConfigFromTemplate(testCase)

    [cfg, templateFile, root, cleanup] = ...
        localCreateFixture(); %#ok<ASGLU>

    templateBefore = ...
        string(fileread(templateFile));

    result = ...
        soopt.writeStrengthConfiguration( ...
            cfg, ...
            25, ...
            15);

    verifyEqual(testCase, ...
        result.ConfigId, ...
        "m25p_a15p");

    verifyEqual(testCase, ...
        result.FileName, ...
        "m25p_a15p.json");

    verifyTrue(testCase, ...
        result.Created);

    verifyFalse(testCase, ...
        result.ReusedExisting);

    verifyEqual(testCase, ...
        result.ConfigDirectory, ...
        string(fullfile( ...
            root, ...
            "adaptive_generated")));

    verifyTrue(testCase, ...
        isfile(result.ConfigFile));

    verifyEqual(testCase, ...
        string(fileread(templateFile)), ...
        templateBefore);

    loaded = ...
        modelprep.loadForceCapacityConfig( ...
            result.ConfigFile);

    localVerifyCoordinate( ...
        testCase, ...
        loaded.Config, ...
        25, ...
        15);

    verifyEqual(testCase, ...
        string(loaded.Config.DefaultApplyMode), ...
        "target");
end


function testPreservesNonStrengthEntries(testCase)

    [cfg, templateFile, ~, cleanup] = ...
        localCreateFixture(); %#ok<ASGLU>

    template = ...
        modelprep.loadForceCapacityConfig( ...
            templateFile);

    result = ...
        soopt.writeStrengthConfiguration( ...
            cfg, ...
            30, ...
            20);

    generated = ...
        modelprep.loadForceCapacityConfig( ...
            result.ConfigFile);

    templateEntries = ...
        template.Config.Entries(:);

    generatedEntries = ...
        generated.Config.Entries(:);

    verifyEqual(testCase, ...
        numel(generatedEntries), ...
        numel(templateEntries));

    passiveIndex = ...
        find( ...
            string({templateEntries.ObjectType}).' == ...
                "BushingForce", ...
            1);

    verifyNotEmpty(testCase, ...
        passiveIndex);

    verifyEqual(testCase, ...
        generatedEntries(passiveIndex), ...
        templateEntries(passiveIndex));

    preserveIndex = ...
        find( ...
            string({templateEntries.Name}).' == ...
                "preserved_actuator", ...
            1);

    verifyNotEmpty(testCase, ...
        preserveIndex);

    verifyEqual(testCase, ...
        generatedEntries(preserveIndex), ...
        templateEntries(preserveIndex));
end


