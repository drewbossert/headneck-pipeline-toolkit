function testMultipleChannelsProduceChannelDiagnostics(testCase)

    [filePath, cleanup] = ...
        localWriteActivationSto( ...
            [ ...
                0.00  0.20  0.30  0.10
                0.01  1.00  0.40 -1.00
                0.02  1.00  0.50 -0.80
            ], ...
            [ ...
                "time"
                "muscle_1"
                "muscle_2"
                "reserve_1"
            ]); %#ok<ASGLU>

    audit = ...
        opensimrun.auditStaticOptimizationActivations( ...
            filePath);

    verifyFalse(testCase, ...
        audit.Passed);

    verifyEqual(testCase, ...
        audit.SaturatedChannelCount, ...
        2);

    verifyEqual(testCase, ...
        audit.SaturatedValueCount, ...
        3);

    verifyEqual(testCase, ...
        audit.SaturatedLabels, ...
        [ ...
            "muscle_1"
            "reserve_1"
        ]);

    muscleRow = ...
        audit.ChannelSummary.Label == ...
        "muscle_1";

    verifyEqual(testCase, ...
        audit.ChannelSummary.SaturatedSampleCount(muscleRow), ...
        2);

    verifyEqual(testCase, ...
        audit.ChannelSummary.FirstSaturationTime(muscleRow), ...
        0.01, ...
        "AbsTol", ...
        1e-12);

    verifyEqual(testCase, ...
        audit.ChannelSummary.LastSaturationTime(muscleRow), ...
        0.02, ...
        "AbsTol", ...
        1e-12);
end


function testCustomLimitIsSupported(testCase)

    [filePath, cleanup] = ...
        localWriteActivationSto( ...
            [ ...
                0.00  0.70
                0.01  0.80
                0.02  0.75
            ], ...
            ["time" "muscle_1"]); %#ok<ASGLU>

    audit = ...
        opensimrun.auditStaticOptimizationActivations( ...
            filePath, ...
            "SaturationLimit", ...
            0.8, ...
            "SaturationTolerance", ...
            0);

    verifyFalse(testCase, ...
        audit.Passed);

    verifyEqual(testCase, ...
        audit.SaturationThreshold, ...
        0.8, ...
        "AbsTol", ...
        1e-12);
end


