function [filePath, cleanup] = ...
        localWriteActivationSto(data, labels)

    root = ...
        string(fullfile( ...
            tempdir, ...
            "headneck_so_activation_audit_" + ...
            string(java.util.UUID.randomUUID())));

    mkdir(root);

    cleanup = ...
        onCleanup(@() localRemoveTree(root));

    filePath = ...
        string(fullfile( ...
            root, ...
            "test_StaticOptimization_activation.sto"));

    fid = ...
        fopen(filePath, "w");

    assert(fid >= 0, ...
        "StaticOptimizationActivationAuditTest:FileCreateFailed", ...
        "Could not create synthetic STO:\n%s", ...
        filePath);

    cleaner = ...
        onCleanup(@() fclose(fid)); %#ok<NASGU>

    fprintf(fid, "name test_activation\n");
    fprintf(fid, "nRows=%d\n", size(data,1));
    fprintf(fid, "nColumns=%d\n", size(data,2));
    fprintf(fid, "endheader\n");

    fprintf( ...
        fid, ...
        "%s\n", ...
        strjoin( ...
            string(labels(:)).', ...
            sprintf('\t')));

    format = ...
        strjoin( ...
            repmat("%.12g", 1, size(data,2)), ...
            "\t") + ...
        "\n";

    for iRow = 1:size(data,1)

        fprintf( ...
            fid, ...
            format, ...
            data(iRow,:));
    end
end


function localRemoveTree(root)

    if isfolder(root)
        rmdir(root, "s");
    end
end
