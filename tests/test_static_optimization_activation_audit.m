    [filePath, cleanup] = ...
        localWriteActivationSto( ...
            [ ...
                0.00  0.25
                0.01  1.00
                0.02  0.40
            ], ...
            ["time" "muscle_1"]); %#ok<ASGLU>

    audit = ...
        opensimrun.auditStaticOptimizationActivations( ...
            filePath);

    verifyFalse(testCase, ...
        audit.Passed);

    verifyEqual(testCase, ...
        audit.SaturatedValueCount, ...
        1);

    verifyEqual(testCase, ...
        audit.SaturatedChannelCount, ...
        1);

    verifyEqual(testCase, ...
        audit.SaturatedLabels, ...
        "muscle_1");

    verifyEqual(testCase, ...
        audit.FirstSaturationTime, ...
        0.01, ...
        "AbsTol", ...
        1e-12);
end


