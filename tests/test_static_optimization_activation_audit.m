function tests = test_static_optimization_activation_audit
%TEST_STATIC_OPTIMIZATION_ACTIVATION_AUDIT Tests SO saturation detection.

    tests = ...
        functiontests(localfunctions);
end


function testUnsaturatedFilePasses(testCase)

    [filePath, cleanup] = ...
        localWriteActivationSto( ...
            [ ...
                0.00  0.20  0.30
                0.01  0.40 -0.50
                0.02  0.60  0.70
            ], ...
            ["time" "muscle_1" "reserve_1"]); %#ok<ASGLU>

    audit = ...
        opensimrun.auditStaticOptimizationActivations( ...
            filePath);

    verifyTrue(testCase, ...
        audit.Passed);

    verifyEqual(testCase, ...
        audit.SaturatedValueCount, ...
        0);

    verifyEqual(testCase, ...
        audit.SaturatedChannelCount, ...
        0);

    verifyEmpty(testCase, ...
        audit.SaturatedLabels);

    verifyEqual(testCase, ...
        audit.PeakAbsoluteActivation, ...
        0.70, ...
        "AbsTol", ...
        1e-12);

    verifyEqual(testCase, ...
        audit.PeakLabel, ...
        "reserve_1");

    verifyEqual(testCase, ...
        audit.PeakTime, ...
        0.02, ...
        "AbsTol", ...
        1e-12);
end


