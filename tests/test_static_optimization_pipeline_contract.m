function tests = test_static_optimization_pipeline_contract
%TEST_STATIC_OPTIMIZATION_PIPELINE_CONTRACT Process-4 contract tests.
%
% These tests verify configuration, resolved paths, dependencies, canonical
% stage layout, and worker availability without executing OpenSim.

    tests = functiontests(localfunctions);
end


function testStaticOptimizationConfigExists(testCase)

    cfg = ...
        localLoadConfig();

    verifyTrue(testCase, ...
        isfield( ...
            cfg.pipeline, ...
            "staticOptimization"));

    soCfg = ...
        cfg.pipeline.staticOptimization;

    requiredFields = [
        "requireForceOutput"
        "requireActivationOutput"
        "timeToleranceSec"
    ];

    verifyTrue(testCase, ...
        all(isfield( ...
            soCfg, ...
            cellstr(requiredFields))));

    verifyTrue(testCase, ...
        soCfg.requireForceOutput);

    verifyTrue(testCase, ...
        soCfg.requireActivationOutput);

    verifyEqual(testCase, ...
        soCfg.timeToleranceSec, ...
        1e-6);
end


