function testProcess4PathsUseCanonicalStageLayout(testCase)

    cfg = ...
        localTestConfig();

    trial = ...
        pipeline.resolveTrialContext( ...
            cfg, ...
            45, ...
            1);

    expectedProcess4Directory = ...
        string(fullfile( ...
            cfg.outputRoot, ...
            "45deg", ...
            "trial01", ...
            "04_static_optimization"));

    expectedResultsDirectory = ...
        string(fullfile( ...
            expectedProcess4Directory, ...
            "results"));

    expectedQcDirectory = ...
        string(fullfile( ...
            expectedProcess4Directory, ...
            "qc"));

    verifyEqual(testCase, ...
        trial.Paths.StaticOptimization.Directory, ...
        expectedProcess4Directory);

    verifyEqual(testCase, ...
        trial.Paths.StaticOptimization.ResultsDirectory, ...
        expectedResultsDirectory);

    verifyEqual(testCase, ...
        trial.Paths.StaticOptimization.QcDirectory, ...
        expectedQcDirectory);

    verifyEqual(testCase, ...
        trial.Paths.StaticOptimization.SetupFile, ...
        string(fullfile( ...
            expectedProcess4Directory, ...
            "45deg_trial01_so_setup.xml")));

    verifyEqual(testCase, ...
        trial.Paths.StaticOptimization.OutputAuditCsv, ...
        string(fullfile( ...
            expectedQcDirectory, ...
            "static_optimization_output_audit.csv")));

    verifyEqual(testCase, ...
        trial.Paths.StaticOptimization.CheckpointFile, ...
        string(fullfile( ...
            expectedQcDirectory, ...
            "static_optimization_run_checkpoint.mat")));
end


function testProcess3CheckpointFeedsProcess4(testCase)

    cfg = ...
        localTestConfig();

    trial = ...
        pipeline.resolveTrialContext( ...
            cfg, ...
            cfg.conditions(1), ...
            cfg.trials(1));

    process3Checkpoint = ...
        trial.Paths.StaticOptimizationPrep.CheckpointFile;

    process4Setup = ...
        trial.Paths.StaticOptimization.SetupFile;

    verifyTrue(testCase, ...
        contains( ...
            process3Checkpoint, ...
            "03_static_optimization_prep"));

    verifyTrue(testCase, ...
        contains( ...
            process4Setup, ...
            "04_static_optimization"));

    verifyNotEqual(testCase, ...
        string(fileparts(process3Checkpoint)), ...
        string(fileparts(process4Setup)));
end


