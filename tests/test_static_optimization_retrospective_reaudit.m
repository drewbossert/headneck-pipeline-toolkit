function tests = test_static_optimization_retrospective_reaudit
%TEST_STATIC_OPTIMIZATION_RETROSPECTIVE_REAUDIT Tests saved-result re-audit.

    tests = ...
        functiontests(localfunctions);
end


function testReauditDemotesSaturatedLegacyTrial(testCase)

    [cfg, configRoot, cleanup] = ...
        localCreateProject(); %#ok<ASGLU>

    summary = ...
        localCreateLegacySummary( ...
            configRoot, ...
            "m25p_a50p", ...
            25, ...
            50, ...
            [0; 15], ...
            [1; 1], ...
            [0.50; 1.00]);

    localWriteLegacyBatchSummary( ...
        configRoot, ...
        summary);

    report = ...
        soopt.reauditStaticOptimizationConfigurations( ...
            cfg, ...
            "PrintProgress", ...
            false);

    verifyEqual(testCase, ...
        report.Status, ...
        "REAUDITED");

    verifyEqual(testCase, ...
        report.TrialsAudited, ...
        2);

    verifyEqual(testCase, ...
        report.TrialsSaturated, ...
        1);

    verifyEqual(testCase, ...
        report.TrialsDemoted, ...
        1);

    verifyEqual(testCase, ...
        report.TrialsSucceededAfterReaudit, ...
        1);

    verifyFalse(testCase, ...
        report.ConfigurationFeasible);

    updated = ...
        readtable( ...
            localSummaryCsv(configRoot), ...
            "TextType", ...
            "string");

    verifyEqual(testCase, ...
        logical(updated.Succeeded), ...
        [true; false]);

    verifyEqual(testCase, ...
        string(updated.Status), ...
        [ ...
            "completed"
            "activation_saturation"
        ]);

    verifyEqual(testCase, ...
        logical(updated.ActivationSaturationPassed), ...
        [true; false]);

    verifyEqual(testCase, ...
        updated.SaturatedChannelCount, ...
        [0; 1]);

    checkpointFile = ...
        string(updated.CheckpointFile(2));

    verifyTrue(testCase, ...
        ismissing(checkpointFile) || ...
        strlength(checkpointFile) == 0);

    auditCsv = ...
        string(updated.ActivationAuditCsv);

    verifyTrue(testCase, ...
        all(isfile(auditCsv)));

    verifyTrue(testCase, ...
        isfile(report.BackupCsv));

    verifyTrue(testCase, ...
        isfile(report.BackupMat));

    loaded = ...
        load( ...
            localSummaryMat(configRoot), ...
            "batchSummary");

    verifyFalse(testCase, ...
        loaded.batchSummary.Succeeded);

    verifyTrue(testCase, ...
        isfield( ...
            loaded.batchSummary, ...
            "ActivationSaturationReaudit"));

    reauditMetadata = ...
        loaded.batchSummary.ActivationSaturationReaudit;

    verifyEqual(testCase, ...
        reauditMetadata.SchemaVersion, ...
        2);

    verifyEqual(testCase, ...
        reauditMetadata.SaturationThreshold, ...
        0.999, ...
        "AbsTol", ...
        1e-12);

    verifyFalse(testCase, ...
        isfield(reauditMetadata, "SaturationLimit"));

    verifyFalse(testCase, ...
        isfield(reauditMetadata, "SaturationTolerance"));
end


