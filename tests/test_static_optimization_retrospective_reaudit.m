    verifyFalse(testCase, ...
        logical(updated.Succeeded));

    verifyEqual(testCase, ...
        string(updated.Status), ...
        "failed");

    verifyEqual(testCase, ...
        string(updated.ErrorIdentifier), ...
        "Existing:Failure");

    verifyEqual(testCase, ...
        report.TrialsDemoted, ...
        0);
