    summary.Status(1) = ...
        "failed";

    summary.ErrorIdentifier(1) = ...
        "Existing:Failure";

    writetable( ...
        summary, ...
        localSummaryCsv(configRoot));

    report = ...
        soopt.reauditStaticOptimizationConfigurations( ...
