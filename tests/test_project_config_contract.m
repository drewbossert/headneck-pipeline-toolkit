        cfg.pipeline.staticOptimization.activationSaturationThreshold, ...
        0.999);

    verifyFalse(testCase, ...
        isfield( ...
            cfg.pipeline.staticOptimization, ...
            "activationSaturationLimit"));

    verifyFalse(testCase, ...
        isfield( ...
            cfg.pipeline.staticOptimization, ...
            "activationSaturationTolerance"));
end


