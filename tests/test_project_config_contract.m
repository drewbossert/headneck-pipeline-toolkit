function tests = test_project_config_contract
%TEST_PROJECT_CONFIG_CONTRACT Validate the canonical configuration schema.

    tests = functiontests(localfunctions);
end


function testDefaultStudyDesign(testCase)

    cfg = localLoadWithoutLocal();

    verifyEqual(testCase, ...
        cfg.configSchemaVersion, ...
        4);

    verifyEqual(testCase, ...
        cfg.conditions, ...
        [0 15 30 45]);

    verifyEqual(testCase, ...
        cfg.trials, ...
        1:5);
end


function testCanonicalBatchNamespace(testCase)

    cfg = localLoadWithoutLocal();

    verifyTrue(testCase, ...
        isfield(cfg, "batchProcessing"));

    verifyTrue(testCase, ...
        isfield(cfg.batchProcessing, "enableParallel"));

    verifyTrue(testCase, ...
        isfield(cfg.batchProcessing, "maxWorkers"));

    verifyFalse(testCase, ...
        isfield(cfg, "enableParallel"));

    verifyFalse(testCase, ...
        isfield(cfg, "maxWorkers"));
end


function testStagePolicyExists(testCase)

    cfg = localLoadWithoutLocal();

    verifyEqual(testCase, ...
        cfg.pipeline.initializationIk.timeRangeSec, ...
        [0.00 19.99]);

    verifyEqual(testCase, ...
