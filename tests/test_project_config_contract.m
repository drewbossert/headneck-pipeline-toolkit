function cfg = localLoadWithoutLocal()

    projectRoot = ...
        string(fileparts(fileparts(mfilename("fullpath"))));

    defaultsFile = ...
        string(fullfile( ...
            projectRoot, ...
            "config", ...
            "project_defaults.m"));

    cfg = struct;

    run(defaultsFile);
end
