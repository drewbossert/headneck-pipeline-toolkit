function tests = test_strength_grid_plan
%TEST_STRENGTH_GRID_PLAN Contract tests for inference-based grid planning.

    tests = ...
        functiontests(localfunctions);
end


function testBuildsFullDeterministicGrid(testCase)

    summary = ...
        localSummaryTable( ...
            "m50p_a75p", ...
            50, ...
            75, ...
            true, ...
            true);

    plan = ...
        soopt.buildStrengthGridPlan( ...
            summary, ...
            [50 25], ...
            [75 25 50]);

    verifyEqual(testCase, ...
        height(plan), ...
        6);

    verifyEqual(testCase, ...
        plan.ConfigId, ...
        [
            "m25p_a25p"
            "m25p_a50p"
            "m25p_a75p"
            "m50p_a25p"
            "m50p_a50p"
            "m50p_a75p"
        ]);
end


function testAssessedFeasibleAndInferredFeasibleStates(testCase)

    summary = ...
        localSummaryTable( ...
            "m25p_a50p", ...
            25, ...
            50, ...
            true, ...
            true);

    plan = ...
        soopt.buildStrengthGridPlan( ...
            summary, ...
            [25 50], ...
            [25 50 75]);

    row = ...
        plan.ConfigId == "m25p_a50p";

    verifyEqual(testCase, ...
        plan.GridStatus(row), ...
        "ASSESSED_FEASIBLE");

    verifyFalse(testCase, ...
        plan.NeedsAssessment(row));

    row = ...
        plan.ConfigId == "m50p_a75p";

    verifyEqual(testCase, ...
        plan.GridStatus(row), ...
        "INFERRED_FEASIBLE");

    verifyFalse(testCase, ...
        plan.NeedsAssessment(row));

    verifyEqual(testCase, ...
        plan.FeasibleInferenceSources(row), ...
        "m25p_a50p");

    row = ...
        plan.ConfigId == "m25p_a25p";

    verifyEqual(testCase, ...
        plan.GridStatus(row), ...
        "UNKNOWN");

    verifyTrue(testCase, ...
        plan.NeedsAssessment(row));
end


