function testIncompleteExistingConfigurationCanStillBeInferred(testCase)

    summary = ...
        localSummaryTable( ...
            [
                "m25p_a50p"
                "m50p_a75p"
            ], ...
            [25; 50], ...
            [50; 75], ...
            [true; false], ...
            [true; false]);

    plan = ...
        soopt.buildStrengthGridPlan( ...
            summary, ...
            [25 50], ...
            [50 75]);

    row = ...
        plan.ConfigId == "m50p_a75p";

    verifyTrue(testCase, ...
        plan.ExistsInSummary(row));

    verifyTrue(testCase, ...
        plan.ExistingIncomplete(row));

    verifyFalse(testCase, ...
        plan.AssessmentComplete(row));

    verifyEqual(testCase, ...
        plan.GridStatus(row), ...
        "INFERRED_FEASIBLE");

    verifyFalse(testCase, ...
        plan.NeedsAssessment(row));
end


