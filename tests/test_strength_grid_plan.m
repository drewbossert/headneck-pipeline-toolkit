function testInferenceSourcesAreDeterministicallySorted(testCase)

    summary = ...
        localSummaryTable( ...
            [
                "m50p_a25p"
                "m25p_a50p"
                "m25p_a25p"
            ], ...
            [50; 25; 25], ...
            [25; 50; 25], ...
            [true; true; true], ...
            [true; true; true]);

    plan = ...
        soopt.buildStrengthGridPlan( ...
            summary, ...
            [25 50 75], ...
            [25 50 75]);

    row = ...
        plan.ConfigId == "m75p_a75p";

    verifyEqual(testCase, ...
        plan.FeasibleInferenceSources(row), ...
        "m25p_a25p;m25p_a50p;m50p_a25p");
end


function testMonotonicityViolationStopsPlanning(testCase)

    summary = ...
        localSummaryTable( ...
            [
                "m25p_a50p"
                "m50p_a75p"
            ], ...
            [25; 50], ...
            [50; 75], ...
            [true; true], ...
            [true; false]);

    verifyError(testCase, ...
        @() soopt.buildStrengthGridPlan( ...
            summary, ...
            [25 50], ...
            [50 75]), ...
        "StrengthGridPlan:MonotonicityViolation");
end


function testEmptySummaryLeavesAllPointsUnknown(testCase)

    summary = ...
        localSummaryTable( ...
            strings(0,1), ...
            zeros(0,1), ...
            zeros(0,1), ...
            false(0,1), ...
            false(0,1));

    plan = ...
        soopt.buildStrengthGridPlan( ...
            summary, ...
            [25 50], ...
            [25 50]);

    verifyEqual(testCase, ...
        height(plan), ...
        4);

    verifyTrue(testCase, ...
        all(plan.GridStatus == "UNKNOWN"));

    verifyTrue(testCase, ...
        all(plan.NeedsAssessment));
end


function testDuplicateGridValuesRejected(testCase)

    summary = ...
        localSummaryTable( ...
            strings(0,1), ...
            zeros(0,1), ...
            zeros(0,1), ...
            false(0,1), ...
            false(0,1));

    verifyError(testCase, ...
        @() soopt.buildStrengthGridPlan( ...
            summary, ...
            [25 25 50], ...
            [25 50]), ...
        "StrengthGridPlan:InvalidMuscleGrid");
end


function T = localSummaryTable( ...
        configId, musclePercent, actuatorPercent, ...
        assessmentComplete, isFeasible)

    ConfigId = ...
        string(configId(:));

    MusclePercent = ...
        double(musclePercent(:));

    ActuatorPercent = ...
        double(actuatorPercent(:));

    AssessmentComplete = ...
        logical(assessmentComplete(:));

    IsFeasible = ...
        logical(isFeasible(:));

    T = ...
        table( ...
            ConfigId, ...
            MusclePercent, ...
            ActuatorPercent, ...
            AssessmentComplete, ...
            IsFeasible);
end
