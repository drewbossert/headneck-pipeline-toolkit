function testSharedContextIsStrengthIndependent(testCase)

    cfg = ...
        localTestConfig();

    trial = ...
        pipeline.resolveTrialContext( ...
            cfg, ...
            cfg.conditions(1), ...
            cfg.trials(1));

    [sharedTrial, sharedCfg] = ...
        pipeline.resolveStaticOptimizationSharedTrialContext( ...
            cfg, ...
            trial.ConditionDeg, ...
            trial.TrialNumber);

    verifyFalse(testCase, ...
        sharedCfg.forceCapacity.enabled);

    verifyFalse(testCase, ...
        sharedTrial.StrengthConfigEnabled);

    verifyEqual(testCase, ...
        sharedTrial.Paths.ModelB.ModelBFile, ...
        trial.Paths.ModelB.ModelBFile);

    verifyEqual(testCase, ...
        sharedTrial.Paths.ModelB.FinalIkMotionFile, ...
        trial.Paths.ModelB.FinalIkMotionFile);

    verifyNotEqual(testCase, ...
        sharedTrial.Paths.StaticOptimizationPrep.Directory, ...
        trial.Paths.StaticOptimizationPrep.Directory);

    verifyTrue(testCase, ...
        contains( ...
            sharedTrial.Paths.StaticOptimizationPrep.Directory, ...
            "03_static_optimization_shared_prep"));

    verifyFalse(testCase, ...
        contains( ...
            sharedTrial.Paths.StaticOptimizationPrep.Directory, ...
            "static_optimization_configs"));
end


