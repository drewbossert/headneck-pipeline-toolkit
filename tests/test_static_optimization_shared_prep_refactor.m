function source = localReadFunctionSource(functionName)

    functionFile = ...
        which(functionName);

    verifyFunctionFile = ...
        string(functionFile);

    assert(strlength(verifyFunctionFile) > 0, ...
        "SharedPrepRefactorTest:FunctionMissing", ...
        "Function was not found: %s", ...
        functionName);

    source = ...
        string(fileread(functionFile));
end
