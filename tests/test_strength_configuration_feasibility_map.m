function testInvalidParetoStateRejected(testCase)

    T = ...
        table( ...
            "m25p_a25p", ...
            25, ...
            25, ...
            false, ...
            false, ...
            true, ...
            'VariableNames', { ...
                'ConfigId', ...
                'MusclePercent', ...
                'ActuatorPercent', ...
                'AssessmentComplete', ...
                'IsFeasible', ...
                'IsParetoOptimal'});

    verifyError(testCase, ...
        @() soopt.plotFeasibilityMap( ...
            T, ...
            "Visible", "off"), ...
        "StrengthFeasibilityMap:InvalidParetoState");
end


function T = localClassifiedTable()

    ConfigId = [
        "m25p_a25p"
        "m25p_a50p"
        "m25p_a75p"
        "m50p_a50p"
        "m50p_a75p"
    ];

    MusclePercent = ...
        [25; 25; 25; 50; 50];

    ActuatorPercent = ...
        [25; 50; 75; 50; 75];

    AssessmentComplete = ...
        [false; true; true; true; true];

    IsFeasible = ...
        [false; false; true; true; true];

    IsParetoOptimal = ...
        [false; false; true; true; false];

    T = ...
        table( ...
            ConfigId, ...
            MusclePercent, ...
            ActuatorPercent, ...
            AssessmentComplete, ...
            IsFeasible, ...
            IsParetoOptimal);
end
