function tests = test_callable_static_optimization_batches
%TEST_CALLABLE_STATIC_OPTIMIZATION_BATCHES Refactor contract tests.
%
% These tests verify the callable Process-3/4 batch architecture without
% executing OpenSim.

    tests = ...
        functiontests(localfunctions);
end


function testCallableBatchFunctionsAreResolvable(testCase)

    verifyNotEmpty(testCase, ...
        which("pipeline.runStaticOptimizationPrepBatch"));

    verifyNotEmpty(testCase, ...
        which("pipeline.runStaticOptimizationBatch"));
end


function testProcess3CallableUsesCanonicalTrialWorker(testCase)

    source = ...
        localReadFunctionSource( ...
            "pipeline.runStaticOptimizationPrepBatch");

    verifyTrue(testCase, ...
        contains( ...
            source, ...
            "pipeline.prepareStaticOptimizationTrial"));

    verifyFalse(testCase, ...
        contains( ...
            source, ...
            "load_project_config("));
end


