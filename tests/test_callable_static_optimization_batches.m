function testProcess3ScriptIsThinWrapper(testCase)

    cfg = ...
        localLoadConfig();

    scriptFile = ...
        string(fullfile( ...
            cfg.batchDirectory, ...
            "batch_run_process_3.m"));

    source = ...
        string(fileread(scriptFile));

    verifyTrue(testCase, ...
        contains( ...
            source, ...
            "load_project_config()"));

    verifyTrue(testCase, ...
        contains( ...
            source, ...
            "pipeline.runStaticOptimizationPrepBatch"));

    verifyFalse(testCase, ...
        contains( ...
            source, ...
            "localRunProcess3Job"));

    verifyFalse(testCase, ...
        contains( ...
            source, ...
            "pipeline.prepareStaticOptimizationTrial"));
end


