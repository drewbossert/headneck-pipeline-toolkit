function testCallableFunctionsExposeAutomationOverrides(testCase)

    process3Source = ...
        localReadFunctionSource( ...
            "pipeline.runStaticOptimizationPrepBatch");

    process4Source = ...
        localReadFunctionSource( ...
            "pipeline.runStaticOptimizationBatch");

    sharedOptions = [
        "Conditions"
        "Trials"
        "Overwrite"
        "EnableParallel"
        "MaxWorkers"
        "ContinueOnError"
        "PoolProfile"
        "ClosePoolWhenFinished"
        "WriteSummary"
        "PrintProgress"
    ];

    for option = sharedOptions.'

        quotedOption = ...
            """" + option + """";

        verifyTrue(testCase, ...
            contains( ...
                process3Source, ...
                quotedOption));

        verifyTrue(testCase, ...
            contains( ...
                process4Source, ...
                quotedOption));
    end

    verifyTrue(testCase, ...
        contains( ...
            process3Source, ...
            '"ExecuteBodyKinematics"'));

    verifyTrue(testCase, ...
        contains( ...
            process4Source, ...
            '"ExecuteStaticOptimization"'));
end


function source = localReadFunctionSource(functionName)

    filePath = ...
        string(which(functionName));

    verifyFile = ...
        isfile(filePath);

    assert(verifyFile, ...
        "CallableBatchTest:FunctionNotFound", ...
        "Could not resolve function source for %s.", ...
        functionName);

    source = ...
        string(fileread(filePath));
end


function cfg = localLoadConfig()

    repositoryRoot = ...
        string(fileparts(fileparts( ...
            mfilename("fullpath"))));

    addpath(repositoryRoot);

    cfg = ...
        load_project_config( ...
            "RequireLocalConfig", false, ...
            "ValidatePaths", false);
end
