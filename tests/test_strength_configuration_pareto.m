function tests = test_strength_configuration_pareto
%TEST_STRENGTH_CONFIGURATION_PARETO Contract tests for Pareto classification.

    tests = ...
        functiontests(localfunctions);
end


function testIdentifiesNondominatedFeasibleConfigurations(testCase)

    T = ...
        localSummaryTable( ...
            [
                "m25p_a75p"
                "m50p_a50p"
                "m50p_a75p"
            ], ...
            [25; 50; 50], ...
            [75; 50; 75], ...
            [true; true; true], ...
            [true; true; true]);

    T = ...
        soopt.findParetoFrontier(T);

    verifyEqual(testCase, ...
        T.IsParetoEligible, ...
        [true; true; true]);

    verifyEqual(testCase, ...
        T.IsParetoOptimal, ...
        [true; true; false]);

    row = ...
        T.ConfigId == "m50p_a75p";

    verifyEqual(testCase, ...
        T.DominatedByCount(row), ...
        2);

    verifyEqual(testCase, ...
        T.DominatingConfigIds(row), ...
        "m25p_a75p;m50p_a50p");
end


function testInfeasibleConfigurationsDoNotDominate(testCase)

    T = ...
        localSummaryTable( ...
            [
                "m25p_a25p"
                "m50p_a50p"
            ], ...
            [25; 50], ...
            [25; 50], ...
            [true; true], ...
            [false; true]);

    T = ...
        soopt.findParetoFrontier(T);

    rowInfeasible = ...
        T.ConfigId == "m25p_a25p";

    rowFeasible = ...
        T.ConfigId == "m50p_a50p";

    verifyFalse(testCase, ...
        T.IsParetoEligible(rowInfeasible));

    verifyFalse(testCase, ...
        T.IsParetoOptimal(rowInfeasible));

    verifyTrue(testCase, ...
        T.IsParetoOptimal(rowFeasible));

    verifyEqual(testCase, ...
        T.DominatedByCount(rowFeasible), ...
        0);

    verifyEqual(testCase, ...
        T.DominatingConfigIds(rowFeasible), ...
        "");
end


