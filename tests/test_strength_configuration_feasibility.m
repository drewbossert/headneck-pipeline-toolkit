function tests = test_strength_configuration_feasibility
%TEST_STRENGTH_CONFIGURATION_FEASIBILITY Contract tests for SO feasibility.
%
% These tests use synthetic Process-4 batch summaries. No OpenSim execution
% is required.

    tests = ...
        functiontests(localfunctions);
end


function testCompleteSuccessfulBatchIsFeasible(testCase)

    [cfg, configRow, cleanup] = ...
        localCreateConfiguration(); %#ok<ASGLU>

    summary = ...
        localBaseSummary(cfg, configRow);

    localWriteSummary( ...
        configRow, ...
        summary);

    result = ...
        soopt.evaluateFeasibility( ...
            configRow, ...
            cfg);

    verifyTrue(testCase, ...
        result.AssessmentComplete);

    verifyTrue(testCase, ...
        result.IsFeasible);

    verifyEqual(testCase, ...
        result.Status, ...
        "FEASIBLE");

    verifyEqual(testCase, ...
        result.ExpectedTrials, ...
        4);

    verifyEqual(testCase, ...
        result.SummaryRows, ...
        4);

    verifyEqual(testCase, ...
        result.SucceededTrials, ...
        4);

    verifyEqual(testCase, ...
        result.FailedTrials, ...
        0);

    verifyEqual(testCase, ...
        result.OutputAuditFailedTrials, ...
        0);
end


function testFullProcess4StyleSummaryIsFeasible(testCase)

    [cfg, configRow, cleanup] = ...
        localCreateConfiguration(); %#ok<ASGLU>

    summary = ...
        localBaseSummary(cfg, configRow);

    nRows = ...
        height(summary);

    summary.TrialStem = ...
        compose( ...
            "%02gdeg_trial%02d", ...
            summary.ConditionDeg, ...
            summary.TrialNumber);

    summary.DurationSeconds = ...
        ones(nRows,1);

    summary.StaticOptimizationDurationSeconds = ...
        ones(nRows,1);

    summary.Process3CheckpointFile = ...
        repmat("checkpoint.mat", nRows, 1);

    summary.StaticOptimizationSetupFile = ...
        repmat("setup.xml", nRows, 1);

    summary.ResultsDirectory = ...
        repmat("results", nRows, 1);

    summary.ForceFile = ...
        repmat("force.sto", nRows, 1);

    summary.ActivationFile = ...
        repmat("activation.sto", nRows, 1);

    summary.ForceRows = ...
        repmat(401, nRows, 1);

    summary.ActivationRows = ...
        repmat(401, nRows, 1);

    summary.CheckpointFile = ...
        repmat("run_checkpoint.mat", nRows, 1);

    summary.ErrorIdentifier = ...
        strings(nRows,1);

    summary.ErrorMessage = ...
        strings(nRows,1);

    localWriteSummary( ...
        configRow, ...
        summary);

    result = ...
        soopt.evaluateFeasibility( ...
            configRow, ...
            cfg);

    verifyTrue(testCase, ...
        result.AssessmentComplete);

    verifyTrue(testCase, ...
        result.IsFeasible);

    verifyEqual(testCase, ...
        result.Status, ...
        "FEASIBLE");

    verifyEqual(testCase, ...
        result.SummaryRows, ...
        4);
end


function testStaticOptimizationFailureIsInfeasible(testCase)

    [cfg, configRow, cleanup] = ...
        localCreateConfiguration(); %#ok<ASGLU>

    summary = ...
        localBaseSummary(cfg, configRow);

    failureRow = ...
        summary.ConditionDeg == 15 & ...
        summary.TrialNumber == 1;

    verifyEqual(testCase, ...
        nnz(failureRow), ...
        1);

    summary.Succeeded(failureRow) = ...
        false;

    summary.Status(failureRow) = ...
        "failed";

    summary.OutputAuditPassed(failureRow) = ...
        false;

    localWriteSummary( ...
        configRow, ...
        summary);

    result = ...
        soopt.evaluateFeasibility( ...
            configRow, ...
            cfg);

    verifyTrue(testCase, ...
        result.AssessmentComplete);

    verifyFalse(testCase, ...
        result.IsFeasible);

    verifyEqual(testCase, ...
        result.Status, ...
        "INFEASIBLE_SO_FAILURE");

    verifyEqual(testCase, ...
        result.FailedTrials, ...
        1);

    verifyEqual(testCase, ...
        result.FailedTrialKeys, ...
        "15deg|trial01");

    % OutputAuditPassed=false on a failed SO run is not double-counted as
    % an independent output-audit failure.
    verifyEqual(testCase, ...
        result.OutputAuditFailedTrials, ...
        0);
end


