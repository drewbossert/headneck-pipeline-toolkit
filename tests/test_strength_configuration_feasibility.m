function [cfg, configRow, cleanup] = localCreateConfiguration()

    root = ...
        string(fullfile( ...
            tempdir, ...
            "headneck_strength_feasibility_" + ...
            string(java.util.UUID.randomUUID())));

    mkdir(root);

    cleanup = ...
        onCleanup(@() localRemoveTree(root));

    cfg = struct;

    cfg.outputRoot = ...
        root;

    cfg.conditions = ...
        [0 15];

    cfg.trials = ...
        [1 2];

    configRoot = ...
        string(fullfile( ...
            root, ...
            "static_optimization_configs", ...
            "m50p_a75p"));

    batchQcDirectory = ...
        string(fullfile( ...
            configRoot, ...
            "batch_qc"));

    mkdir(batchQcDirectory);

    configRow = ...
        table( ...
            "m50p_a75p", ...
            50, ...
            75, ...
            string(fullfile( ...
                batchQcDirectory, ...
                "process_4_static_optimization_summary.csv")), ...
            'VariableNames', { ...
                'ConfigId', ...
                'MusclePercent', ...
                'ActuatorPercent', ...
                'Process4SummaryCsv'});
end


function summary = localBaseSummary(cfg, configRow)

    [conditionGrid, trialGrid] = ...
        ndgrid( ...
            cfg.conditions, ...
            cfg.trials);

    ConditionDeg = ...
        conditionGrid(:);

    TrialNumber = ...
        trialGrid(:);

    nRows = ...
        numel(ConditionDeg);

    ConfigId = ...
        repmat( ...
            string(configRow.ConfigId), ...
            nRows, ...
            1);

    MusclePercent = ...
        repmat( ...
            double(configRow.MusclePercent), ...
            nRows, ...
            1);

    ActuatorPercent = ...
        repmat( ...
            double(configRow.ActuatorPercent), ...
            nRows, ...
            1);

    Status = ...
        repmat( ...
            "completed", ...
            nRows, ...
            1);

    Succeeded = ...
        true(nRows,1);

    OutputAuditPassed = ...
        true(nRows,1);

    summary = ...
        table( ...
            ConditionDeg, ...
            TrialNumber, ...
            ConfigId, ...
            MusclePercent, ...
            ActuatorPercent, ...
            Status, ...
            Succeeded, ...
            OutputAuditPassed);
end


function localWriteSummary(configRow, summary)

    summaryFile = ...
        string(configRow.Process4SummaryCsv);

    summaryDirectory = ...
        string(fileparts(summaryFile));

    if ~isfolder(summaryDirectory)

        mkdir(summaryDirectory);
    end

    writetable( ...
        summary, ...
        summaryFile);
end


function localRemoveTree(root)

    if isfolder(root)

        rmdir(root, "s");
    end
end
