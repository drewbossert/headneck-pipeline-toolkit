            result, ...
            cfg, ...
            "ExportFigure", ...
            false), ...
        "StrengthGridWrite:OutputExists");
end


function testOverwriteReplacesExistingArtifacts(testCase)

    [cfg, result, cleanup] = ...
        localCreateFixture(); %#ok<ASGLU>

    outputs = ...
        soopt.writeStrengthGridAnalysis( ...
            result, ...
            cfg, ...
            "ExportFigure", ...
            false);

    firstText = ...
        string(fileread( ...
            outputs.SummaryCsv));

    result.Summary.FeasibilityReason(:) = ...
        "updated";

    outputs = ...
        soopt.writeStrengthGridAnalysis( ...
            result, ...
            cfg, ...
            "Overwrite", ...
            true, ...
            "ExportFigure", ...
            false);

    secondText = ...
        string(fileread( ...
            outputs.SummaryCsv));

    verifyNotEqual(testCase, ...
        secondText, ...
        firstText);

    verifyFalse(testCase, ...
        outputs.FigureExported);

    verifyEqual(testCase, ...
        outputs.FigurePng, ...
        "");
end


function testCustomOutputDirectoryIsSupported(testCase)

    [cfg, result, cleanup] = ...
        localCreateFixture(); %#ok<ASGLU>

    customDirectory = ...
        string(fullfile( ...
            fileparts(cfg.outputRoot), ...
            "custom_grid_report"));

    outputs = ...
        soopt.writeStrengthGridAnalysis( ...
            result, ...
            cfg, ...
            "OutputDirectory", ...
            customDirectory, ...
            "ExportFigure", ...
            false);

    verifyEqual(testCase, ...
        outputs.OutputDirectory, ...
        customDirectory);

    verifyTrue(testCase, ...
        isfile(outputs.AnalysisMat));
end


