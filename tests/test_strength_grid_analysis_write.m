function tests = test_strength_grid_analysis_write
%TEST_STRENGTH_GRID_ANALYSIS_WRITE Tests strength-grid persistence layer.

    tests = ...
        functiontests(localfunctions);
end


function testWritesCompleteAnalysisPackage(testCase)

    [cfg, result, cleanup] = ...
        localCreateFixture(); %#ok<ASGLU>

    outputs = ...
        soopt.writeStrengthGridAnalysis( ...
            result, ...
            cfg);

    verifyTrue(testCase, ...
        isfolder(outputs.OutputDirectory));

    requiredFiles = [
        outputs.SummaryCsv
        outputs.ParetoFrontierCsv
        outputs.GridPlanCsv
        outputs.ProposalsCsv
        outputs.MonotonicityViolationsCsv
        outputs.CandidateConfigPoolCsv
        outputs.MissingConfigCombinationsCsv
        outputs.FigurePng
        outputs.AnalysisMat
    ];

    verifyTrue(testCase, ...
        all(isfile(requiredFiles)));

    verifyTrue(testCase, ...
        outputs.FigureExported);

    writtenSummary = ...
        readtable( ...
            outputs.SummaryCsv, ...
            "TextType", ...
            "string");

    verifyEqual(testCase, ...
        string(writtenSummary.ConfigId), ...
        result.Summary.ConfigId);

    writtenPareto = ...
        readtable( ...
            outputs.ParetoFrontierCsv, ...
            "TextType", ...
            "string");

    verifyEqual(testCase, ...
        string(writtenPareto.ConfigId), ...
        result.ParetoFrontier.ConfigId);

    loaded = ...
        load( ...
            outputs.AnalysisMat, ...
            "analysisSnapshot");

    verifyEqual(testCase, ...
        loaded.analysisSnapshot.SchemaVersion, ...
        1);

    verifyEqual(testCase, ...
        loaded.analysisSnapshot.Result.Figure, ...
        []);

    verifyEqual(testCase, ...
        loaded.analysisSnapshot.Result.Axes, ...
        []);

    verifyEqual(testCase, ...
        loaded.analysisSnapshot.Result.PlanningStatus, ...
        result.PlanningStatus);

    verifyEqual(testCase, ...
        loaded.analysisSnapshot.ProjectConfig.outputRoot, ...
        cfg.outputRoot);
end


