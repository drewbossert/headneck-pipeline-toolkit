function tests = test_strength_proposed_config_resolution
%TEST_STRENGTH_PROPOSED_CONFIG_RESOLUTION Tests proposal-to-JSON mapping.

    tests = ...
        functiontests(localfunctions);
end


function testResolvesTopProposalToExactJson(testCase)

    [result, root, cleanup] = ...
        localCreateFixture(); %#ok<ASGLU>

    selection = ...
        soopt.resolveProposedStrengthConfig( ...
            result);

    verifyEqual(testCase, ...
        selection.SchemaVersion, ...
        1);

    verifyEqual(testCase, ...
        selection.PriorityRank, ...
        1);

    verifyEqual(testCase, ...
        selection.ConfigId, ...
        "m15p_a15p");

    verifyEqual(testCase, ...
        selection.MusclePercent, ...
        15);

    verifyEqual(testCase, ...
        selection.ActuatorPercent, ...
        15);

    verifyEqual(testCase, ...
        selection.FileName, ...
        "m15p_a15p.json");

    verifyTrue(testCase, ...
        isfile(selection.ConfigFile));

    verifyEqual(testCase, ...
        selection.ConfigFile, ...
        string(fullfile( ...
            root, ...
            "m15p_a15p.json")));

    verifyEqual(testCase, ...
        selection.Proposal.ConfigId, ...
        "m15p_a15p");

    verifyEqual(testCase, ...
        selection.PoolConfiguration.ConfigId, ...
        "m15p_a15p");
end


