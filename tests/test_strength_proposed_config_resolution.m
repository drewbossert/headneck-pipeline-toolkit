function [result, root, cleanup] = localCreateFixture()

    root = ...
        string(fullfile( ...
            tempdir, ...
            "headneck_proposal_resolve_" + ...
            string(java.util.UUID.randomUUID())));

    mkdir(root);

    cleanup = ...
        onCleanup(@() localRemoveTree(root));

    configIds = [
        "m15p_a15p"
        "m20p_a10p"
        "m25p_a25p"
    ];

    musclePercent = ...
        [15; 20; 25];

    actuatorPercent = ...
        [15; 10; 25];

    fileName = ...
        configIds + ...
        ".json";

    configFile = ...
        strings(numel(configIds),1);

    for iConfig = 1:numel(configIds)

        configFile(iConfig) = ...
            string(fullfile( ...
                root, ...
                fileName(iConfig)));

        localWriteJson( ...
            configFile(iConfig));
    end

    configurations = ...
        table( ...
            configIds, ...
            musclePercent, ...
            actuatorPercent, ...
            fileName, ...
            configFile, ...
            'VariableNames', { ...
                'ConfigId', ...
                'MusclePercent', ...
                'ActuatorPercent', ...
                'FileName', ...
                'ConfigFile'});

    PriorityRank = ...
        [1; 2];

    ConfigId = [
        "m15p_a15p"
        "m20p_a10p"
    ];

    MusclePercent = ...
        [15; 20];

    ActuatorPercent = ...
        [15; 10];

    ExistingIncomplete = ...
        [false; true];

    FeasibleOutcomeResolvedCount = ...
        [4; 3];

    InfeasibleOutcomeResolvedCount = ...
        [3; 4];

    WorstCaseResolvedCount = ...
        [3; 3];

    BestCaseResolvedCount = ...
        [4; 4];

    TotalResolutionPotential = ...
        [7; 7];

    ResolutionImbalance = ...
        [1; 1];

    GridCenterDistance = ...
        [0.1; 0.2];

    proposals = ...
        table( ...
            PriorityRank, ...
            ConfigId, ...
            MusclePercent, ...
            ActuatorPercent, ...
            ExistingIncomplete, ...
            FeasibleOutcomeResolvedCount, ...
            InfeasibleOutcomeResolvedCount, ...
            WorstCaseResolvedCount, ...
            BestCaseResolvedCount, ...
            TotalResolutionPotential, ...
            ResolutionImbalance, ...
            GridCenterDistance);

    configPool = struct;

    configPool.SchemaVersion = ...
        1;

    configPool.ConfigDirectory = ...
        root;

    configPool.Configurations = ...
        configurations;

    result = struct;

    result.SchemaVersion = ...
        1;

    result.ConfigPool = ...
        configPool;

    result.Proposals = ...
        proposals;

    result.PlanningAvailable = ...
        true;

    result.PlanningStatus = ...
        "AVAILABLE";

    result.PlanningReason = ...
        "synthetic";
end


function localWriteJson(filePath)

    fid = ...
        fopen(filePath, "w");

    assert(fid >= 0, ...
        "StrengthProposalResolveTest:FileCreateFailed", ...
        "Could not create synthetic JSON:\n%s", ...
        filePath);

    cleanup = ...
        onCleanup(@() fclose(fid)); %#ok<NASGU>

    fprintf(fid, "{}\n");
end


function localRemoveTree(root)

    if isfolder(root)

        rmdir(root, "s");
    end
end
