function tests = test_static_optimization_result_discovery
%TEST_STATIC_OPTIMIZATION_RESULT_DISCOVERY Contract tests for result search.
%
% These tests create a temporary synthetic output tree; no OpenSim
% execution is required.

    tests = ...
        functiontests(localfunctions);
end


function testDiscoversCanonicalForceResult(testCase)

    [cfg, cleanup] = ...
        localCreateSyntheticProject(); %#ok<ASGLU>

    localMakeTrialArtifacts( ...
        cfg.outputRoot, ...
        15, ...
        3, ...
        true, ...
        true, ...
        true);

    T = ...
        pipeline.discoverStaticOptimizationResults( ...
            cfg);

    verifyEqual(testCase, ...
        height(T), ...
        1);

    verifyEqual(testCase, ...
        T.ConditionDeg, ...
        15);

    verifyEqual(testCase, ...
        T.TrialNumber, ...
        3);

    verifyEqual(testCase, ...
        T.TrialStem, ...
        "15deg_trial03");

    verifyTrue(testCase, ...
        T.ReadyForQc);

    verifyEqual(testCase, ...
        T.Status, ...
        "ready");
end


function testForceResultWithoutCompanionsIsStillDetected(testCase)

    [cfg, cleanup] = ...
        localCreateSyntheticProject(); %#ok<ASGLU>

    localMakeTrialArtifacts( ...
        cfg.outputRoot, ...
        0, ...
        1, ...
        false, ...
        false, ...
        false);

    T = ...
        pipeline.discoverStaticOptimizationResults( ...
            cfg);

    verifyEqual(testCase, ...
        height(T), ...
        1);

    verifyFalse(testCase, ...
        T.ReadyForQc);

    verifyTrue(testCase, ...
        contains( ...
            T.Status, ...
            "activation_file_count=0"));

    verifyTrue(testCase, ...
        contains( ...
            T.Status, ...
            "model_c_missing"));

    verifyTrue(testCase, ...
        contains( ...
            T.Status, ...
            "event_summary_missing"));
end


function testExclusionDoesNotHideDetection(testCase)

    [cfg, cleanup] = ...
        localCreateSyntheticProject(); %#ok<ASGLU>

    localMakeTrialArtifacts( ...
        cfg.outputRoot, ...
        30, ...
        4, ...
        true, ...
        true, ...
        true);

    T = ...
        pipeline.discoverStaticOptimizationResults( ...
            cfg, ...
            "ExcludedTrials", ...
                [30 4]);

    verifyEqual(testCase, ...
        height(T), ...
        1);

    verifyTrue(testCase, ...
        T.ReadyForQc);

    verifyTrue(testCase, ...
        T.ExcludedByConfig);

    verifyTrue(testCase, ...
        contains( ...
            T.Status, ...
            "excluded_by_config"));
end


function testNestedBatchRootsArePreserved(testCase)

    [cfg, cleanup] = ...
        localCreateSyntheticProject(); %#ok<ASGLU>

    batchA = ...
        string(fullfile( ...
            cfg.outputRoot, ...
            "batch_A"));

    batchB = ...
        string(fullfile( ...
            cfg.outputRoot, ...
            "batch_B"));

    localMakeTrialArtifacts( ...
        batchA, ...
        0, ...
        1, ...
        true, ...
        true, ...
        true);

    localMakeTrialArtifacts( ...
        batchB, ...
        15, ...
        1, ...
        true, ...
        true, ...
        true);

    T = ...
        pipeline.discoverStaticOptimizationResults( ...
            cfg);

    verifyEqual(testCase, ...
        height(T), ...
        2);

    verifyEqual(testCase, ...
        numel(unique(T.BatchRoot)), ...
        2);
end


function [cfg, cleanup] = localCreateSyntheticProject()

    root = ...
        string(fullfile( ...
            tempdir, ...
            "headneck_so_discovery_" + ...
            string(java.util.UUID.randomUUID())));

    mkdir(root);

    cleanup = ...
        onCleanup(@() localRemoveTree(root));

    cfg = struct;
    cfg.outputRoot = root;
end


function localMakeTrialArtifacts( ...
        root, conditionDeg, trialNumber, ...
        includeActivation, includeModel, includeEvents)

    conditionTag = ...
        string(sprintf( ...
            "%02ddeg", ...
            conditionDeg));

    trialTag = ...
        string(sprintf( ...
            "trial%02d", ...
            trialNumber));

    trialStem = ...
        conditionTag + ...
        "_" + ...
        trialTag;

    trialRoot = ...
        string(fullfile( ...
            root, ...
            conditionTag, ...
            trialTag));

    resultsDirectory = ...
        string(fullfile( ...
            trialRoot, ...
            "04_static_optimization", ...
            "results"));

    mkdir(resultsDirectory);

    localTouch( ...
        fullfile( ...
            resultsDirectory, ...
            "SO_" + ...
            trialStem + ...
            "_StaticOptimization_force.sto"));

    if includeActivation

        localTouch( ...
            fullfile( ...
                resultsDirectory, ...
                "SO_" + ...
                trialStem + ...
                "_StaticOptimization_activation.sto"));
    end

    prepDirectory = ...
        string(fullfile( ...
            trialRoot, ...
            "03_static_optimization_prep"));

    if includeModel

        mkdir(prepDirectory);

        localTouch( ...
            fullfile( ...
                prepDirectory, ...
                trialStem + ...
                "_modelC_static_optimization.osim"));
    end

    if includeEvents

        eventDirectory = ...
            string(fullfile( ...
                prepDirectory, ...
                "head_support_force", ...
                "qc"));

        if ~isfolder(eventDirectory)
            mkdir(eventDirectory);
        end

        localTouch( ...
            fullfile( ...
                eventDirectory, ...
                "contact_event_detection_summary.csv"));
    end
end


function localTouch(filePath)

    [folder, ~, ~] = ...
        fileparts(filePath);

    if ~isfolder(folder)
        mkdir(folder);
    end

    fid = ...
        fopen(filePath, "w");

    assert(fid >= 0, ...
        "SOResultDiscoveryTest:FileCreateFailed", ...
        "Could not create synthetic test file:\n%s", ...
        filePath);

    cleaner = ...
        onCleanup(@() fclose(fid)); %#ok<NASGU>

    fprintf(fid, "test\n");
end


function localRemoveTree(root)

    if isfolder(root)
        rmdir(root, "s");
    end
end
