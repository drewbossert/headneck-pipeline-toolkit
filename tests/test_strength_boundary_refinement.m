function testOnlyOneOutcomeClassReturnsEmpty(testCase)

    feasibleOnly = ...
        localSummary( ...
            [ ...
                "m20p_a20p"
                "m30p_a30p"
            ], ...
            [20; 30], ...
            [20; 30], ...
            [true; true], ...
            [true; true]);

    infeasibleOnly = ...
        localSummary( ...
            [ ...
                "m20p_a20p"
                "m30p_a30p"
            ], ...
            [20; 30], ...
            [20; 30], ...
            [true; true], ...
            [false; false]);

    verifyEqual(testCase, ...
        height( ...
            soopt.proposeBoundaryRefinement( ...
                feasibleOnly)), ...
        0);

    verifyEqual(testCase, ...
        height( ...
            soopt.proposeBoundaryRefinement( ...
                infeasibleOnly)), ...
        0);
end


function testExistingIncompleteCoordinateCanBeProposed(testCase)

    summary = ...
        localSummary( ...
            [ ...
                "m25p_a15p"
                "m25p_a20p"
                "m25p_a25p"
            ], ...
            [25; 25; 25], ...
            [15; 20; 25], ...
            [true; false; true], ...
            [false; false; true]);

    proposals = ...
        soopt.proposeBoundaryRefinement( ...
            summary);

    verifyEqual(testCase, ...
        proposals.ConfigId, ...
        "m25p_a20p");

    verifyTrue(testCase, ...
        proposals.ExistingIncomplete);

    verifyEqual(testCase, ...
        proposals.ExistingConfigId, ...
        "m25p_a20p");
end


function testExplicitBoundsRestrictVirtualLattice(testCase)

    summary = ...
        localSummary( ...
            [ ...
                "m10p_a10p"
                "m40p_a40p"
            ], ...
            [10; 40], ...
            [10; 40], ...
            [true; true], ...
            [false; true]);

    proposals = ...
        soopt.proposeBoundaryRefinement( ...
            summary, ...
            "MuscleBounds", ...
            [20 30], ...
            "ActuatorBounds", ...
            [20 30], ...
            "MaxProposals", ...
            Inf);

    verifyTrue(testCase, ...
        all( ...
            proposals.MusclePercent >= 20 & ...
            proposals.MusclePercent <= 30));

    verifyTrue(testCase, ...
        all( ...
            proposals.ActuatorPercent >= 20 & ...
            proposals.ActuatorPercent <= 30));
end


function summary = ...
        localSummary( ...
            configId, ...
            musclePercent, ...
            actuatorPercent, ...
            assessmentComplete, ...
            isFeasible)

    ConfigId = ...
        string(configId(:));

    MusclePercent = ...
        double(musclePercent(:));

    ActuatorPercent = ...
        double(actuatorPercent(:));

    AssessmentComplete = ...
        logical(assessmentComplete(:));

    IsFeasible = ...
        logical(isFeasible(:));

    summary = ...
        table( ...
            ConfigId, ...
            MusclePercent, ...
            ActuatorPercent, ...
            AssessmentComplete, ...
            IsFeasible);
end
