function tests = test_strength_boundary_refinement
%TEST_STRENGTH_BOUNDARY_REFINEMENT Tests adaptive numeric boundary proposals.

    tests = ...
        functiontests(localfunctions);
end


function testSimpleVerticalBracketProposesMidpoint(testCase)

    summary = ...
        localSummary( ...
            [ ...
                "m25p_a15p"
                "m25p_a25p"
            ], ...
            [25; 25], ...
            [15; 25], ...
            [true; true], ...
            [false; true]);

    proposals = ...
        soopt.proposeBoundaryRefinement( ...
            summary);

    verifyEqual(testCase, ...
        height(proposals), ...
        1);

    verifyEqual(testCase, ...
        proposals.ConfigId, ...
        "m25p_a20p");

    verifyEqual(testCase, ...
        proposals.MusclePercent, ...
        25);

    verifyEqual(testCase, ...
        proposals.ActuatorPercent, ...
        20);

    verifyEqual(testCase, ...
        proposals.LowerInfeasibleConfigId, ...
        "m25p_a15p");

    verifyEqual(testCase, ...
        proposals.UpperFeasibleConfigId, ...
        "m25p_a25p");
end


