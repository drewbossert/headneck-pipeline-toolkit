function testNonlinearBoundaryUsesLocalEvidenceOnly(testCase)

    summary = ...
        localSummary( ...
            [ ...
                "m10p_a40p"
                "m10p_a50p"
                "m25p_a15p"
                "m25p_a25p"
                "m40p_a05p"
                "m40p_a15p"
            ], ...
            [10; 10; 25; 25; 40; 40], ...
            [40; 50; 15; 25; 5; 15], ...
            true(6,1), ...
            [false; true; false; true; false; true]);

    proposals = ...
        soopt.proposeBoundaryRefinement( ...
            summary, ...
            "MaxProposals", ...
            Inf);

    verifyGreaterThan(testCase, ...
        height(proposals), ...
        0);

    verifyFalse(testCase, ...
        any( ...
            proposals.MusclePercent == 25 & ...
            proposals.ActuatorPercent == 15));

    verifyFalse(testCase, ...
        any( ...
            proposals.MusclePercent == 25 & ...
            proposals.ActuatorPercent == 25));

    verifyTrue(testCase, ...
        all( ...
            mod(proposals.MusclePercent, 5) == 0));

    verifyTrue(testCase, ...
        all( ...
            mod(proposals.ActuatorPercent, 5) == 0));

    verifyTrue(testCase, ...
        all( ...
            strlength(proposals.LowerInfeasibleConfigId) > 0));

    verifyTrue(testCase, ...
        all( ...
            strlength(proposals.UpperFeasibleConfigId) > 0));
end


