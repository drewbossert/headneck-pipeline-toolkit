function [cfg, configDirectory, cleanup] = ...
        localCreateProject(conditions, trials)

    root = ...
        string(fullfile( ...
            tempdir, ...
            "headneck_grid_search_" + ...
            string(java.util.UUID.randomUUID())));

    outputRoot = ...
        string(fullfile( ...
            root, ...
            "output"));

    configDirectory = ...
        string(fullfile( ...
            root, ...
            "force_configs"));

    mkdir(outputRoot);
    mkdir(configDirectory);

    cleanup = ...
        onCleanup(@() localRemoveTree(root));

    cfg = struct;

    cfg.outputRoot = ...
        outputRoot;

    cfg.conditions = ...
        double(conditions);

    cfg.trials = ...
        double(trials);

    cfg.overwriteExisting = ...
        false;

    cfg.forceCapacity = struct;

    cfg.forceCapacity.enabled = ...
        false;

    cfg.forceCapacity.configFile = ...
        string(fullfile( ...
            configDirectory, ...
            "m25p_a50p.json"));

    cfg.forceCapacity.applyMode = ...
        "target";

    cfg.batchProcessing = struct;

    cfg.batchProcessing.enableParallel = ...
        false;

    cfg.batchProcessing.maxWorkers = ...
        1;

    cfg.batchProcessing.continueOnError = ...
        true;

    cfg.batchProcessing.poolProfile = ...
        "local";

    cfg.batchProcessing.closePoolWhenFinished = ...
        false;

    cfg.optimization = struct;
    cfg.optimization.staticOptimization = struct;

    searchCfg = struct;
    searchCfg.searchMode = "fixed_grid";
    searchCfg.maxIterations = 20;
    searchCfg.dryRun = false;
    searchCfg.overwriteIncompleteConfiguration = true;

    searchCfg.fixedGrid = struct;
    searchCfg.fixedGrid.configDirectory = "";

    searchCfg.adaptiveBoundary = struct;
    searchCfg.adaptiveBoundary.incrementPercent = 5;
    searchCfg.adaptiveBoundary.muscleBounds = [];
    searchCfg.adaptiveBoundary.actuatorBounds = [];
    searchCfg.adaptiveBoundary.configDirectory = "";
    searchCfg.adaptiveBoundary.templateConfigFile = "";

    searchCfg.output = struct;
    searchCfg.output.writeAnalysis = true;
    searchCfg.output.analysisDirectory = "";
    searchCfg.output.exportFigure = true;
    searchCfg.output.figureResolution = 300;
    searchCfg.output.writeSearchHistory = true;

    searchCfg.printProgress = true;

    cfg.optimization.staticOptimization = ...
        searchCfg;
end


function localCreatePool( ...
        configDirectory, ...
        muscleGrid, ...
        actuatorGrid)

    for muscle = muscleGrid

        for actuator = actuatorGrid

            localTouchJson( ...
                configDirectory, ...
                localConfigId( ...
                    muscle, ...
                    actuator) + ...
                ".json");
        end
    end
end


function localWriteCompleteSummary( ...
        cfg, ...
        configId, ...
        musclePercent, ...
        actuatorPercent, ...
        isFeasible)

    ConditionDeg = ...
        cfg.conditions(:);

    nConditions = ...
        numel(ConditionDeg);

    TrialNumber = ...
        repmat( ...
            cfg.trials(1), ...
            nConditions, ...
            1);

    ConfigId = ...
        repmat( ...
            string(configId), ...
            nConditions, ...
            1);

    MusclePercent = ...
        repmat( ...
            musclePercent, ...
            nConditions, ...
            1);

    ActuatorPercent = ...
        repmat( ...
            actuatorPercent, ...
            nConditions, ...
            1);

    Succeeded = ...
        true(nConditions,1);

    Status = ...
        repmat( ...
            "completed", ...
            nConditions, ...
            1);

    OutputAuditPassed = ...
        true(nConditions,1);

    if ~isFeasible

        Succeeded(end) = ...
            false;

        Status(end) = ...
            "activation_saturation";
    end

    summary = ...
        table( ...
            ConfigId, ...
            MusclePercent, ...
            ActuatorPercent, ...
            ConditionDeg, ...
            TrialNumber, ...
            Succeeded, ...
            Status, ...
            OutputAuditPassed);

    localWriteSummaryTable( ...
        cfg, ...
        configId, ...
        summary);
end


function localWriteIncompleteSummary( ...
        cfg, ...
        configId, ...
        musclePercent, ...
        actuatorPercent)

    ConfigId = ...
        string(configId);

    MusclePercent = ...
        musclePercent;

    ActuatorPercent = ...
        actuatorPercent;

    ConditionDeg = ...
        cfg.conditions(1);

    TrialNumber = ...
        cfg.trials(1);

    Succeeded = ...
        true;

    Status = ...
        "completed";

    OutputAuditPassed = ...
        true;

    summary = ...
        table( ...
            ConfigId, ...
            MusclePercent, ...
            ActuatorPercent, ...
            ConditionDeg, ...
            TrialNumber, ...
            Succeeded, ...
            Status, ...
            OutputAuditPassed);

    localWriteSummaryTable( ...
        cfg, ...
        configId, ...
        summary);
end


function localWriteSummaryTable( ...
        cfg, ...
        configId, ...
        summary)

    batchQcDirectory = ...
        string(fullfile( ...
            cfg.outputRoot, ...
            "static_optimization_configs", ...
            configId, ...
            "batch_qc"));

    mkdir(batchQcDirectory);

    summaryCsv = ...
        string(fullfile( ...
            batchQcDirectory, ...
            "process_4_static_optimization_summary.csv"));

    writetable( ...
        summary, ...
        summaryCsv);
end


function configId = localConfigId( ...
        musclePercent, ...
        actuatorPercent)

    configId = ...
        "m" + ...
        string(musclePercent) + ...
        "p_a" + ...
        compose("%02d", actuatorPercent) + ...
        "p";
end


function localTouchJson(directory, fileName)

    filePath = ...
        string(fullfile( ...
            directory, ...
            fileName));

    fid = ...
        fopen(filePath, "w");

    assert(fid >= 0, ...
        "StrengthGridSearchTest:FileCreateFailed", ...
        "Could not create synthetic JSON:\n%s", ...
        filePath);

    cleaner = ...
        onCleanup(@() fclose(fid)); %#ok<NASGU>

    fprintf(fid, "{}\n");
end


function source = localReadFunctionSource(functionName)

    filePath = ...
        string(which(functionName));

    assert(isfile(filePath), ...
        "StrengthGridSearchTest:FunctionNotFound", ...
        "Could not resolve function source for %s.", ...
        functionName);

    source = ...
        string(fileread(filePath));
end


function localRemoveTree(root)

    if isfolder(root)

        rmdir(root, "s");
    end
end
