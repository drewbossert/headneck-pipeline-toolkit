function tests = test_strength_grid_search_controller
%TEST_STRENGTH_GRID_SEARCH_CONTROLLER Tests closed-loop controller contract.
%
% The focused suite does not execute OpenSim. It exercises initial analysis,
% proposal resolution, stop logic, dry-run behavior, and source-level
% integration with the callable Process-3/4 batch APIs.

    tests = ...
        functiontests(localfunctions);
end


function testDryRunResolvesCurrentTopProposal(testCase)

    [cfg, configDirectory, cleanup] = ...
        localCreateProject( ...
            [0], ...
            1); %#ok<ASGLU>

    localCreatePool( ...
        configDirectory, ...
        [10 20], ...
        [10 20]);

    localWriteCompleteSummary( ...
        cfg, ...
        "m20p_a20p", ...
        20, ...
        20, ...
        true);

    expectedAnalysis = ...
        soopt.analyzeStrengthGrid( ...
            cfg, ...
            "ConfigDirectory", ...
                configDirectory, ...
            "CreateFigure", ...
                false);

    expectedSelection = ...
        soopt.resolveProposedStrengthConfig( ...
            expectedAnalysis);

    search = ...
        soopt.runStrengthGridSearch( ...
            cfg, ...
            "ConfigDirectory", ...
                configDirectory, ...
            "DryRun", ...
                true, ...
            "PrintProgress", ...
                false);

    verifyEqual(testCase, ...
        search.StopStatus, ...
        "SEARCH_DRY_RUN_READY");

    verifyEqual(testCase, ...
        search.ExecutedIterations, ...
        0);

    verifyEqual(testCase, ...
        height(search.Iterations), ...
        1);

    verifyEqual(testCase, ...
        search.Iterations.ConfigId, ...
        expectedSelection.ConfigId);

    verifyEqual(testCase, ...
        search.Iterations.ConfigFile, ...
        expectedSelection.ConfigFile);

    verifyEqual(testCase, ...
        search.Iterations.Status, ...
        "dry_run_selected");
end


