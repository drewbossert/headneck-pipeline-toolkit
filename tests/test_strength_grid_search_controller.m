function testControllerUsesResolvedProjectDefaults(testCase)

    source = ...
        localReadFunctionSource( ...
            "soopt.runStrengthGridSearch");

    sourceWithoutWhitespace = ...
        regexprep( ...
            erase(source, "..."), ...
            "\s+", ...
            "");

    verifyTrue(testCase, ...
        contains( ...
            sourceWithoutWhitespace, ...
            "soopt.resolveStrengthGridSearchControllerConfig(" + ...
            "projectCfg)"));

    optionNames = [
        "ConfigDirectory"
        "SearchMode"
        "BoundaryIncrementPercent"
        "BoundaryMuscleBounds"
        "BoundaryActuatorBounds"
        "AdaptiveConfigDirectory"
        "AdaptiveTemplateConfigFile"
        "MaxIterations"
        "DryRun"
        "OverwriteIncompleteConfiguration"
        "WriteAnalysis"
        "AnalysisOutputDirectory"
        "ExportFigure"
        "FigureResolution"
        "WriteSearchHistory"
        "PrintProgress"
    ];

    for optionName = optionNames'

        expectedParserPrefix = ...
            "addParameter(parser,""" + ...
            optionName + ...
            """,controllerDefaults." + ...
            optionName + ...
            ",";

        verifyTrue(testCase, ...
            contains( ...
                sourceWithoutWhitespace, ...
                expectedParserPrefix), ...
            "Parser default for " + ...
            optionName + ...
            " was not sourced from controllerDefaults.");
    end
end


