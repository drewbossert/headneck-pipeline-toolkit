function testSummaryHasNoAdditionalFilesystemSideEffects(testCase)

    [cfg, cleanup] = ...
        localCreateSyntheticProject(); %#ok<ASGLU>

    configRow = ...
        localMakeConfig( ...
            cfg, ...
            "m50p_a75p");

    verifyFalse(testCase, ...
        isfolder(configRow.BatchQcDirectory));

    soopt.summarizeStrengthConfigurations( ...
        cfg);

    verifyFalse(testCase, ...
        isfolder(configRow.BatchQcDirectory));

    verifyFalse(testCase, ...
        isfolder(configRow.AnalysisDirectory));
end


function [cfg, cleanup] = localCreateSyntheticProject()

    root = ...
        string(fullfile( ...
            tempdir, ...
            "headneck_strength_summary_" + ...
            string(java.util.UUID.randomUUID())));

    mkdir(root);

    cleanup = ...
        onCleanup(@() localRemoveTree(root));

    cfg = struct;

    cfg.outputRoot = ...
        root;

    cfg.conditions = ...
        [0 15];

    cfg.trials = ...
        [1 2];
end


function configRow = localMakeConfig(cfg, configId)

    info = ...
        pipeline.parseStrengthConfigName( ...
            configId + ".json");

    collectionRoot = ...
        string(fullfile( ...
            cfg.outputRoot, ...
            "static_optimization_configs"));

    configRoot = ...
        string(fullfile( ...
            collectionRoot, ...
            configId));

    mkdir(configRoot);

    batchQcDirectory = ...
        string(fullfile( ...
            configRoot, ...
            "batch_qc"));

    process4SummaryCsv = ...
        string(fullfile( ...
            batchQcDirectory, ...
            "process_4_static_optimization_summary.csv"));

    process4SummaryMat = ...
        string(fullfile( ...
            batchQcDirectory, ...
            "process_4_static_optimization_summary.mat"));

    analysisDirectory = ...
        string(fullfile( ...
            configRoot, ...
            "static_optimization_analysis"));

    configRow = ...
        table( ...
            info.ConfigId, ...
            info.MusclePercent, ...
            info.ActuatorPercent, ...
            configRoot, ...
            batchQcDirectory, ...
            process4SummaryCsv, ...
            false, ...
            process4SummaryMat, ...
            false, ...
            analysisDirectory, ...
            false, ...
            'VariableNames', { ...
                'ConfigId', ...
                'MusclePercent', ...
                'ActuatorPercent', ...
                'ConfigRoot', ...
                'BatchQcDirectory', ...
                'Process4SummaryCsv', ...
                'Process4SummaryCsvExists', ...
                'Process4SummaryMat', ...
                'Process4SummaryMatExists', ...
                'AnalysisDirectory', ...
                'AnalysisExists'});
end


function summary = localBaseProcess4Summary(cfg, configRow)

    [conditionGrid, trialGrid] = ...
        ndgrid( ...
            cfg.conditions, ...
            cfg.trials);

    ConditionDeg = ...
        conditionGrid(:);

    TrialNumber = ...
        trialGrid(:);

    nRows = ...
        numel(ConditionDeg);

    ConfigId = ...
        repmat( ...
            string(configRow.ConfigId), ...
            nRows, ...
            1);

    MusclePercent = ...
        repmat( ...
            double(configRow.MusclePercent), ...
            nRows, ...
            1);

    ActuatorPercent = ...
        repmat( ...
            double(configRow.ActuatorPercent), ...
            nRows, ...
            1);

    Status = ...
        repmat( ...
            "completed", ...
            nRows, ...
            1);

    Succeeded = ...
        true(nRows,1);

    OutputAuditPassed = ...
        true(nRows,1);

    summary = ...
        table( ...
            ConditionDeg, ...
            TrialNumber, ...
            ConfigId, ...
            MusclePercent, ...
            ActuatorPercent, ...
            Status, ...
            Succeeded, ...
            OutputAuditPassed);
end


function localWriteSummary(configRow, summary)

    summaryFile = ...
        string(configRow.Process4SummaryCsv);

    summaryDirectory = ...
        string(fileparts(summaryFile));

    if ~isfolder(summaryDirectory)

        mkdir(summaryDirectory);
    end

    writetable( ...
        summary, ...
        summaryFile);
end


function localRemoveTree(root)

    if isfolder(root)

        rmdir(root, "s");
    end
end
