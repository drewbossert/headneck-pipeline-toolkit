function tests = test_strength_configuration_summary
%TEST_STRENGTH_CONFIGURATION_SUMMARY Contract tests for grid summarization.
%
% These tests build temporary canonical configuration trees and synthetic
% Process-4 summary CSVs. No OpenSim execution is required.

    tests = ...
        functiontests(localfunctions);
end


function testSummarizesMixedConfigurationStates(testCase)

    [cfg, cleanup] = ...
        localCreateSyntheticProject(); %#ok<ASGLU>

    % Feasible configuration.
    row25_75 = ...
        localMakeConfig( ...
            cfg, ...
            "m25p_a75p");

    summary25_75 = ...
        localBaseProcess4Summary( ...
            cfg, ...
            row25_75);

    localWriteSummary( ...
        row25_75, ...
        summary25_75);

    % Infeasible configuration due to one SO failure.
    row50_50 = ...
        localMakeConfig( ...
            cfg, ...
            "m50p_a50p");

    summary50_50 = ...
        localBaseProcess4Summary( ...
            cfg, ...
            row50_50);

    failureRow = ...
        summary50_50.ConditionDeg == 15 & ...
        summary50_50.TrialNumber == 1;

    verifyEqual(testCase, ...
        nnz(failureRow), ...
        1);

    summary50_50.Succeeded(failureRow) = ...
        false;

    summary50_50.Status(failureRow) = ...
        "failed";

    summary50_50.OutputAuditPassed(failureRow) = ...
        false;

    localWriteSummary( ...
        row50_50, ...
        summary50_50);

    % Discovered but not yet evaluated: no Process-4 CSV.
    localMakeConfig( ...
        cfg, ...
        "m50p_a75p");

    T = ...
        soopt.summarizeStrengthConfigurations( ...
            cfg);

    verifyEqual(testCase, ...
        T.ConfigId, ...
        [
            "m25p_a75p"
            "m50p_a50p"
            "m50p_a75p"
        ]);

    row = ...
        T.ConfigId == "m25p_a75p";

    verifyTrue(testCase, ...
        T.AssessmentComplete(row));

    verifyTrue(testCase, ...
        T.IsFeasible(row));

    verifyEqual(testCase, ...
        T.FeasibilityStatus(row), ...
        "FEASIBLE");

    row = ...
        T.ConfigId == "m50p_a50p";

    verifyTrue(testCase, ...
        T.AssessmentComplete(row));

    verifyFalse(testCase, ...
        T.IsFeasible(row));

    verifyEqual(testCase, ...
        T.FeasibilityStatus(row), ...
        "INFEASIBLE_SO_FAILURE");

    verifyEqual(testCase, ...
        T.FailedTrials(row), ...
        1);

    verifyEqual(testCase, ...
        T.FailedTrialKeys(row), ...
        "15deg|trial01");

    row = ...
        T.ConfigId == "m50p_a75p";

    verifyFalse(testCase, ...
        T.AssessmentComplete(row));

    verifyFalse(testCase, ...
        T.IsFeasible(row));

    verifyEqual(testCase, ...
        T.FeasibilityStatus(row), ...
        "INCOMPLETE_MISSING_BATCH_SUMMARY");
end


function testPreservesDiscoveryMetadata(testCase)

    [cfg, cleanup] = ...
        localCreateSyntheticProject(); %#ok<ASGLU>

    configRow = ...
        localMakeConfig( ...
            cfg, ...
            "m50p_a75p");

    process4Summary = ...
        localBaseProcess4Summary( ...
            cfg, ...
            configRow);

    localWriteSummary( ...
        configRow, ...
        process4Summary);

    analysisDirectory = ...
        string(fullfile( ...
            configRow.ConfigRoot, ...
            "static_optimization_analysis"));

    mkdir(analysisDirectory);

    T = ...
        soopt.summarizeStrengthConfigurations( ...
            cfg);

    verifyEqual(testCase, ...
        height(T), ...
        1);

    verifyEqual(testCase, ...
        T.ConfigRoot, ...
        configRow.ConfigRoot);

    verifyEqual(testCase, ...
        T.Process4SummaryCsv, ...
        configRow.Process4SummaryCsv);

    verifyTrue(testCase, ...
        T.Process4SummaryCsvExists);

    verifyTrue(testCase, ...
        T.AnalysisExists);

    verifyEqual(testCase, ...
        T.AnalysisDirectory, ...
        analysisDirectory);
end


