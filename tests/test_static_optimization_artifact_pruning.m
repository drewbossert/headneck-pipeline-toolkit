function localTouch(filePath, nBytes)

    parent = fileparts(filePath);

    if ~isfolder(parent)
        mkdir(parent);
    end

    fid = fopen(filePath, "w");

    assert(fid >= 0, ...
        "SOPruneTest:FileCreateFailed", ...
        "Could not create test file:\n%s", ...
        string(filePath));

    cleanup = onCleanup(@() fclose(fid));
    fwrite(fid, zeros(nBytes,1,"uint8"), "uint8");
end


function localRemoveTree(root)

    if isfolder(root)
        rmdir(root, "s");
    end
end
