function testDryRunDoesNotDeleteFiles(testCase)

    [cfg, root, cleanup] = localFixture(); %#ok<ASGLU>
    localPopulate(root, "m25p_a25p");

    cfg.storage.staticOptimization.keepControlsXml = false;

    result = pipeline.pruneStaticOptimizationArtifacts( ...
        cfg, ...
        "DryRun", true, ...
        "PrintProgress", false);

    verifyGreaterThan(testCase, result.DeleteCandidateCount, 0);
    verifyEqual(testCase, result.DeletedFileCount, 0);

    controls = fullfile( ...
        root, "static_optimization_configs", "m25p_a25p", ...
        "00deg", "trial01", "04_static_optimization", "results", ...
        "SO_00deg_trial01_StaticOptimization_controls.xml");

    verifyTrue(testCase, isfile(controls));
end


function testApplyHonorsIndependentPolicies(testCase)

    [cfg, root, cleanup] = localFixture(); %#ok<ASGLU>
    localPopulate(root, "m25p_a25p");

    cfg.storage.staticOptimization.keepControlsXml = false;
    cfg.storage.staticOptimization.keepSetupXml = false;
    cfg.storage.staticOptimization.keepForceSto = true;
    cfg.storage.staticOptimization.keepActivationSto = true;

    cfg.storage.staticOptimizationPrep.keepConfiguredModelC = false;

    cfg.storage.sharedStaticOptimizationPrep.keepNeutralModelC = false;
    cfg.storage.sharedStaticOptimizationPrep.keepBodyKinematics = false;
    cfg.storage.sharedStaticOptimizationPrep.keepComCsv = true;

    result = pipeline.pruneStaticOptimizationArtifacts( ...
        cfg, ...
        "DryRun", false, ...
        "PrintProgress", false);

    verifyEqual(testCase, result.DeleteFailureCount, 0);

    configRoot = fullfile( ...
        root, "static_optimization_configs", "m25p_a25p", ...
        "00deg", "trial01");

    verifyFalse(testCase, isfile(fullfile( ...
        configRoot, "03_static_optimization_prep", ...
        "00deg_trial01_modelC_static_optimization.osim")));

    verifyFalse(testCase, isfile(fullfile( ...
        configRoot, "04_static_optimization", ...
        "00deg_trial01_so_setup.xml")));

    verifyFalse(testCase, isfile(fullfile( ...
        configRoot, "04_static_optimization", "results", ...
        "SO_00deg_trial01_StaticOptimization_controls.xml")));

    verifyTrue(testCase, isfile(fullfile( ...
        configRoot, "04_static_optimization", "results", ...
        "SO_00deg_trial01_StaticOptimization_force.sto")));

    verifyTrue(testCase, isfile(fullfile( ...
        configRoot, "04_static_optimization", "results", ...
        "SO_00deg_trial01_StaticOptimization_activation.sto")));

    sharedRoot = fullfile( ...
        root, "00deg", "trial01", ...
        "03_static_optimization_shared_prep");

    verifyFalse(testCase, isfile(fullfile( ...
        sharedRoot, ...
        "00deg_trial01_modelC_static_optimization.osim")));

    verifyFalse(testCase, isfile(fullfile( ...
        sharedRoot, "body_kinematics", ...
        "00deg_trial01_body_kinematics_setup.xml")));

    verifyFalse(testCase, isfile(fullfile( ...
        sharedRoot, "body_kinematics", "results", ...
        "BodyKinematics_pos_global.sto")));

    verifyTrue(testCase, isfile(fullfile( ...
        sharedRoot, "body_kinematics", "qc", ...
        "skull_com_resampled.csv")));
end


function testQcCheckpointAndEventPoliciesAreIndependent(testCase)

    [cfg, root, cleanup] = localFixture(); %#ok<ASGLU>
    localPopulate(root, "m25p_a25p");

    cfg.storage.staticOptimization.keepQc = false;
    cfg.storage.staticOptimization.keepCheckpoint = true;

    cfg.storage.staticOptimizationPrep.keepQc = false;
    cfg.storage.staticOptimizationPrep.keepCheckpoint = true;

    cfg.storage.sharedStaticOptimizationPrep.keepQc = false;
    cfg.storage.sharedStaticOptimizationPrep.keepCheckpoint = true;
    cfg.storage.sharedStaticOptimizationPrep.keepComCsv = true;
    cfg.storage.sharedStaticOptimizationPrep.keepEventTiming = true;

    pipeline.pruneStaticOptimizationArtifacts( ...
        cfg, ...
        "DryRun", false, ...
        "PrintProgress", false);

    configRoot = fullfile( ...
        root, "static_optimization_configs", "m25p_a25p", ...
        "00deg", "trial01");

    verifyTrue(testCase, isfile(fullfile( ...
        configRoot, "03_static_optimization_prep", "qc", ...
        "model_c_checkpoint.mat")));

    verifyFalse(testCase, isfile(fullfile( ...
        configRoot, "03_static_optimization_prep", "qc", ...
        "modelC_force_capacity_config_audit.csv")));

    verifyTrue(testCase, isfile(fullfile( ...
        configRoot, "04_static_optimization", "qc", ...
        "static_optimization_run_checkpoint.mat")));

    verifyFalse(testCase, isfile(fullfile( ...
        configRoot, "04_static_optimization", "qc", ...
        "static_optimization_output_audit.csv")));

    sharedRoot = fullfile( ...
        root, "00deg", "trial01", ...
        "03_static_optimization_shared_prep");

    verifyTrue(testCase, isfile(fullfile( ...
        sharedRoot, "qc", "model_c_checkpoint.mat")));

    verifyTrue(testCase, isfile(fullfile( ...
        sharedRoot, "body_kinematics", "qc", ...
        "skull_com_raw.csv")));

    verifyTrue(testCase, isfile(fullfile( ...
        sharedRoot, "head_support_force", "qc", ...
        "contact_event_detection_summary.csv")));

    verifyFalse(testCase, isfile(fullfile( ...
        sharedRoot, "head_support_force", "qc", ...
        "hsf_summary.csv")));
end


