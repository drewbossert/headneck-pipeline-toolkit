    cfg = ...
        localLoadConfig();

    verifyTrue(testCase, ...
        isfield(cfg, "hsf"));

    verifyTrue(testCase, ...
        isfield( ...
            cfg.hsf, ...
            "useModelBodyMass"));

    verifyTrue(testCase, ...
        isfield( ...
            cfg.hsf, ...
            "Parameters"));

    requiredFields = [
        "BodyName"
        "SkullMassKg"
        "GravityY"
        "TargetRateHz"
        "RampDuration"
        "RampShape"
        "RadialSign"
        "AzimuthConvention"
        "InterpolationMethod"
        "ForcePrefix"
        "PointPrefix"
    ];

    verifyTrue(testCase, ...
        all(isfield( ...
            cfg.hsf.Parameters, ...
            cellstr(requiredFields))));
end


