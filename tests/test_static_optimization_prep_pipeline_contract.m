function tests = test_static_optimization_prep_pipeline_contract
%TEST_STATIC_OPTIMIZATION_PREP_PIPELINE_CONTRACT Process-3 contract tests.
%
% These tests verify configuration, resolved paths, dependencies, and
% worker availability without executing OpenSim.

    tests = functiontests(localfunctions);
end


function testStaticOptimizationPrepConfigExists(testCase)

    cfg = ...
        localLoadConfig();

    verifyTrue(testCase, ...
        isfield( ...
            cfg.pipeline, ...
            "staticOptimizationPrep"));

    prepCfg = ...
        cfg.pipeline.staticOptimizationPrep;

    verifyTrue(testCase, ...
        isfield( ...
            prepCfg, ...
            "bodyKinematicsLowpassCutoffHz"));

    verifyTrue(testCase, ...
        isfield( ...
            prepCfg, ...
            "timeRangeSec"));

    verifyEqual(testCase, ...
        prepCfg.bodyKinematicsLowpassCutoffHz, ...
        -1);
end


