function cfg = localLoadConfig()

    repositoryRoot = ...
        string(fileparts(fileparts( ...
            mfilename("fullpath"))));

    addpath(repositoryRoot);

    cfg = ...
        load_project_config( ...
            "LocalConfigPolicy", "disabled", ...
            "ValidatePaths", false);
end
