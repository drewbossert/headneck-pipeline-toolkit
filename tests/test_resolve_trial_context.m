function testResolverHasNoFilesystemSideEffects(testCase)

    cfg = localTestConfig();

    uniqueRoot = string(fullfile( ...
        tempdir, ...
        "headneck_trial_context_" + ...
        string(java.util.UUID.randomUUID())));

    cfg.outputRoot = uniqueRoot;

    verifyFalse(testCase, ...
        isfolder(uniqueRoot));

    pipeline.resolveTrialContext( ...
        cfg, 0, 1);

    verifyFalse(testCase, ...
        isfolder(uniqueRoot));
end


