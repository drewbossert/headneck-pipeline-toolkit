function testAllStudyTrialRootsAreUnique(testCase)

    cfg = localTestConfig();

    roots = strings( ...
        numel(cfg.conditions) * ...
        numel(cfg.trials), ...
        1);

    index = 0;

    for conditionDeg = cfg.conditions

        for trialNumber = cfg.trials

            index = index + 1;

            trial = pipeline.resolveTrialContext( ...
                cfg, ...
                conditionDeg, ...
                trialNumber);

            roots(index) = ...
                trial.Paths.TrialRoot;
        end
    end

    verifyEqual(testCase, ...
        numel(unique(roots)), ...
        numel(roots));
end


function cfg = localTestConfig()

    repositoryRoot = ...
        string(fileparts(fileparts(mfilename("fullpath"))));

    addpath(repositoryRoot);

    cfg = load_project_config( ...
        "RequireLocalConfig", false, ...
        "ValidatePaths", false);

    % Keep tests independent of machine-local path existence.
    cfg.rawDataRoot = string(fullfile( ...
        tempdir, ...
        "headneck_raw_data"));

    cfg.outputRoot = string(fullfile( ...
        tempdir, ...
        "headneck_outputs"));

    % Keep baseline path-contract tests independent of project_local.m.
    % Strength-config-specific tests enable a profile explicitly through
    % localEnableStrengthConfig().
    cfg.forceCapacity.enabled = false;
    cfg.forceCapacity.configFile = "";
    cfg.forceCapacity.applyMode = "target";
end

