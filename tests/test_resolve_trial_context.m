function tests = test_resolve_trial_context
%TEST_RESOLVE_TRIAL_CONTEXT Contract tests for canonical trial resolution.

    tests = functiontests(localfunctions);
end


function testCanonicalIdentity(testCase)

    cfg = localTestConfig();

    trial = pipeline.resolveTrialContext( ...
        cfg, 45, 1);

    verifyEqual(testCase, ...
        trial.SchemaVersion, ...
        1);

    verifyEqual(testCase, ...
        trial.ConditionDeg, ...
        45);

    verifyEqual(testCase, ...
        trial.TrialNumber, ...
        1);

    verifyEqual(testCase, ...
        trial.ConditionTag, ...
        "45deg");

    verifyEqual(testCase, ...
        trial.TrialTag, ...
        "trial01");

    verifyEqual(testCase, ...
        trial.TrialStem, ...
        "45deg_trial01");

    verifyEqual(testCase, ...
        trial.DisplayName, ...
        "45 deg, trial 1");
end


