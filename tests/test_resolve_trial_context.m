function testStrengthConfigIsolatesProcess3And4Paths(testCase)

    cfg = ...
        localTestConfig();

    cfg = ...
        localEnableStrengthConfig( ...
            cfg, ...
            "m25p_a75p.json");

    trial = ...
        pipeline.resolveTrialContext( ...
            cfg, ...
            15, ...
            3);

    sharedTrialRoot = ...
        string(fullfile( ...
            cfg.outputRoot, ...
            "15deg", ...
            "trial03"));

    configRoot = ...
        string(fullfile( ...
            cfg.outputRoot, ...
            "static_optimization_configs", ...
            "m25p_a75p"));

    soTrialRoot = ...
        string(fullfile( ...
            configRoot, ...
            "15deg", ...
            "trial03"));

    verifyTrue(testCase, ...
        trial.StrengthConfigEnabled);

    verifyEqual(testCase, ...
        trial.StrengthConfigId, ...
        "m25p_a75p");

    verifyEqual(testCase, ...
        trial.Paths.TrialRoot, ...
        sharedTrialRoot);

    verifyEqual(testCase, ...
        trial.Paths.StrengthConfigRoot, ...
        configRoot);

    verifyEqual(testCase, ...
        trial.Paths.StaticOptimizationTrialRoot, ...
        soTrialRoot);

    verifyEqual(testCase, ...
        trial.Paths.Initialization.Directory, ...
        string(fullfile( ...
            sharedTrialRoot, ...
            "01_initialization_ik")));

    verifyEqual(testCase, ...
        trial.Paths.ModelB.Directory, ...
        string(fullfile( ...
            sharedTrialRoot, ...
            "02_locked_final_ik")));

    verifyEqual(testCase, ...
        trial.Paths.StaticOptimizationPrep.Directory, ...
        string(fullfile( ...
            soTrialRoot, ...
            "03_static_optimization_prep")));

    verifyEqual(testCase, ...
        trial.Paths.StaticOptimization.Directory, ...
        string(fullfile( ...
            soTrialRoot, ...
            "04_static_optimization")));
end

function testStrengthConfigsShareIkButIsolateSoPaths(testCase)

    cfg25_50 = ...
        localEnableStrengthConfig( ...
            localTestConfig(), ...
            "m25p_a50p.json");

    cfg25_75 = ...
        localEnableStrengthConfig( ...
            localTestConfig(), ...
            "m25p_a75p.json");

    trial25_50 = ...
        pipeline.resolveTrialContext( ...
            cfg25_50, ...
            30, ...
            2);

    trial25_75 = ...
        pipeline.resolveTrialContext( ...
            cfg25_75, ...
            30, ...
            2);

    % Configuration-independent stages are identical.
    verifyEqual(testCase, ...
        trial25_50.Paths.Initialization.Directory, ...
        trial25_75.Paths.Initialization.Directory);

    verifyEqual(testCase, ...
        trial25_50.Paths.ModelB.Directory, ...
        trial25_75.Paths.ModelB.Directory);

    % Configuration-dependent stages are isolated.
    verifyNotEqual(testCase, ...
        trial25_50.Paths.StaticOptimizationPrep.Directory, ...
        trial25_75.Paths.StaticOptimizationPrep.Directory);

    verifyNotEqual(testCase, ...
        trial25_50.Paths.StaticOptimization.Directory, ...
        trial25_75.Paths.StaticOptimization.Directory);

    verifyEqual(testCase, ...
        trial25_50.StrengthConfigId, ...
        "m25p_a50p");

    verifyEqual(testCase, ...
        trial25_75.StrengthConfigId, ...
        "m25p_a75p");
end

