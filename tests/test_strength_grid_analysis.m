function [cfg, configDirectory, cleanup] = localCreateProject()

    root = ...
        string(fullfile( ...
            tempdir, ...
            "headneck_grid_analysis_" + ...
            string(java.util.UUID.randomUUID())));

    outputRoot = ...
        string(fullfile( ...
            root, ...
            "output"));

    configDirectory = ...
        string(fullfile( ...
            root, ...
            "force_configs"));

    mkdir(outputRoot);
    mkdir(configDirectory);

    cleanup = ...
        onCleanup(@() localRemoveTree(root));

    cfg = struct;

    cfg.outputRoot = ...
        outputRoot;

    cfg.conditions = ...
        [0 15];

    cfg.trials = ...
        1;

    cfg.forceCapacity = struct;

    cfg.forceCapacity.configFile = ...
        string(fullfile( ...
            root, ...
            "unrelated", ...
            "selected_profile.json"));

    cfg.optimization = struct;
    cfg.optimization.staticOptimization = struct;
    cfg.optimization.staticOptimization.fixedGrid = struct;
    cfg.optimization.staticOptimization.fixedGrid.configDirectory = ...
        configDirectory;
end


function localCreatePool(configDirectory, muscleGrid, actuatorGrid)

    for muscle = muscleGrid
        for actuator = actuatorGrid

            localTouchJson( ...
                configDirectory, ...
                localConfigId( ...
                    muscle, ...
                    actuator) + ...
                ".json");
        end
    end
end


function localWriteConfigSummary( ...
        cfg, configId, musclePercent, actuatorPercent, isFeasible)

    configRoot = ...
        string(fullfile( ...
            cfg.outputRoot, ...
            "static_optimization_configs", ...
            configId));

    batchQcDirectory = ...
        string(fullfile( ...
            configRoot, ...
            "batch_qc"));

    mkdir(batchQcDirectory);

    ConditionDeg = ...
        double(cfg.conditions(:));

    TrialNumber = ...
        repmat( ...
            double(cfg.trials(1)), ...
            numel(ConditionDeg), ...
            1);

    nRows = ...
        numel(ConditionDeg);

    ConfigId = ...
        repmat( ...
            string(configId), ...
            nRows, ...
            1);

    MusclePercent = ...
        repmat( ...
            double(musclePercent), ...
            nRows, ...
            1);

    ActuatorPercent = ...
        repmat( ...
            double(actuatorPercent), ...
            nRows, ...
            1);

    if isFeasible

        Succeeded = ...
            true(nRows,1);

        Status = ...
            repmat( ...
                "completed", ...
                nRows, ...
                1);

        OutputAuditPassed = ...
            true(nRows,1);

    else

        Succeeded = ...
            true(nRows,1);

        Succeeded(end) = ...
            false;

        Status = ...
            repmat( ...
                "completed", ...
                nRows, ...
                1);

        Status(end) = ...
            "activation_saturation";

        OutputAuditPassed = ...
            true(nRows,1);

        OutputAuditPassed(end) = ...
            false;
    end

    summary = ...
        table( ...
            ConfigId, ...
            MusclePercent, ...
            ActuatorPercent, ...
            ConditionDeg, ...
            TrialNumber, ...
            Succeeded, ...
            Status, ...
            OutputAuditPassed);

    summaryCsv = ...
        string(fullfile( ...
            batchQcDirectory, ...
            "process_4_static_optimization_summary.csv"));

    writetable( ...
        summary, ...
        summaryCsv);
end


function configId = localConfigId(musclePercent, actuatorPercent)

    configId = ...
        "m" + ...
        string(musclePercent) + ...
        "p_a" + ...
        compose("%02d", actuatorPercent) + ...
        "p";
end


function localTouchJson(directory, fileName)

    filePath = ...
        string(fullfile( ...
            directory, ...
            fileName));

    fid = ...
        fopen(filePath, "w");

    assert(fid >= 0, ...
        "StrengthGridAnalysisTest:FileCreateFailed", ...
        "Could not create synthetic JSON file:\n%s", ...
        filePath);

    cleaner = ...
        onCleanup(@() fclose(fid)); %#ok<NASGU>

    fprintf(fid, "{}\n");
end


function localRemoveTree(root)

    if isfolder(root)

        rmdir(root, "s");
    end
end
