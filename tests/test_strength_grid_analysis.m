function tests = test_strength_grid_analysis
%TEST_STRENGTH_GRID_ANALYSIS Tests top-level SO grid orchestration.

    tests = ...
        functiontests(localfunctions);
end


function testOrchestratesObservedParetoAndProposal(testCase)

    [cfg, configDirectory, cleanup] = ...
        localCreateProject(); %#ok<ASGLU>

    localCreatePool( ...
        configDirectory, ...
        [25 50], ...
        [50 75]);

    localWriteConfigSummary( ...
        cfg, ...
        "m25p_a75p", ...
        25, ...
        75, ...
        true);

    localWriteConfigSummary( ...
        cfg, ...
        "m50p_a50p", ...
        50, ...
        50, ...
        true);

    localWriteConfigSummary( ...
        cfg, ...
        "m50p_a75p", ...
        50, ...
        75, ...
        true);

    result = ...
        soopt.analyzeStrengthGrid( ...
            cfg, ...
            "CreateFigure", ...
            false);

    verifyEqual(testCase, ...
        result.SchemaVersion, ...
        1);

    verifyTrue(testCase, ...
        result.PlanningAvailable);

    verifyEqual(testCase, ...
        result.PlanningStatus, ...
        "AVAILABLE");

    verifyTrue(testCase, ...
        result.MonotonicityAudit.IsMonotonic);

    verifyEqual(testCase, ...
        result.ParetoFrontier.ConfigId, ...
        [ ...
            "m25p_a75p"
            "m50p_a50p"
        ]);

    verifyEqual(testCase, ...
        result.Proposals.ConfigId, ...
        "m25p_a50p");

    verifyEqual(testCase, ...
        height(result.GridPlan), ...
        4);

    verifyEqual(testCase, ...
        result.ConfigPool.DiscoveredConfigurationCount, ...
        4);
end


function testParetoFrontierContainsOnlyObservedFeasibleRows(testCase)

    [cfg, configDirectory, cleanup] = ...
        localCreateProject(); %#ok<ASGLU>

    localCreatePool( ...
        configDirectory, ...
        [25 50], ...
        [50 75]);

    localWriteConfigSummary( ...
        cfg, ...
        "m25p_a50p", ...
        25, ...
        50, ...
        true);

    result = ...
        soopt.analyzeStrengthGrid( ...
            cfg, ...
            "CreateFigure", ...
            false);

    verifyEqual(testCase, ...
        height(result.ParetoFrontier), ...
        1);

    verifyTrue(testCase, ...
        all(result.ParetoFrontier.AssessmentComplete));

    verifyTrue(testCase, ...
        all(result.ParetoFrontier.IsFeasible));

    verifyTrue(testCase, ...
        all(result.ParetoFrontier.IsParetoOptimal));

    inferredRows = ...
        startsWith( ...
            result.GridPlan.GridStatus, ...
            "INFERRED_");

    verifyGreaterThan(testCase, ...
        nnz(inferredRows), ...
        0);

    verifyFalse(testCase, ...
        any(ismember( ...
            result.GridPlan.ConfigId(inferredRows), ...
            result.ParetoFrontier.ConfigId)));
