        localCreateProject(); %#ok<ASGLU>

    localTouchJson(configDirectory, "m25p_a50p.json");
    localTouchJson(configDirectory, "m25p_a75p.json");
    localTouchJson(configDirectory, "m50p_a50p.json");

    localWriteConfigSummary( ...
        cfg, ...
        "m25p_a75p", ...
        25, ...
        75, ...
        true);

    result = ...
        soopt.analyzeStrengthGrid( ...
            cfg, ...
            "CreateFigure", ...
            false);

    verifyFalse(testCase, ...
        result.ConfigPool.IsCompleteCartesianGrid);

    verifyFalse(testCase, ...
        result.PlanningAvailable);

    verifyEqual(testCase, ...
        result.PlanningStatus, ...
        "UNAVAILABLE_INCOMPLETE_CONFIG_POOL");

    verifyEqual(testCase, ...
        height(result.GridPlan), ...
        0);

    verifyEqual(testCase, ...
        height(result.Proposals), ...
        0);

    verifyEqual(testCase, ...
        height(result.ParetoFrontier), ...
        1);
end


