function tests = test_strength_configuration_monotonicity
%TEST_STRENGTH_CONFIGURATION_MONOTONICITY Tests monotonic feasibility audit.

    tests = ...
        functiontests(localfunctions);
end


function testMonotonicAssessedGridPasses(testCase)

    T = ...
        localSummaryTable( ...
            [
                "m25p_a25p"
                "m25p_a50p"
                "m50p_a25p"
                "m50p_a50p"
            ], ...
            [25; 25; 50; 50], ...
            [25; 50; 25; 50], ...
            [true; true; true; true], ...
            [false; false; false; true]);

    audit = ...
        soopt.auditFeasibilityMonotonicity(T);

    verifyTrue(testCase, ...
        audit.IsMonotonic);

    verifyEqual(testCase, ...
        audit.ViolationCount, ...
        0);

    verifyEqual(testCase, ...
        audit.AssessedConfigurations, ...
        4);

    verifyEqual(testCase, ...
        audit.FeasibleConfigurations, ...
        1);

    verifyEqual(testCase, ...
        audit.InfeasibleConfigurations, ...
        3);

    verifyEqual(testCase, ...
        height(audit.Violations), ...
        0);
end


function testFeasibleLowerAndInfeasibleHigherIsViolation(testCase)

    T = ...
        localSummaryTable( ...
            [
                "m25p_a50p"
                "m50p_a75p"
            ], ...
            [25; 50], ...
            [50; 75], ...
            [true; true], ...
            [true; false]);

    audit = ...
        soopt.auditFeasibilityMonotonicity(T);

    verifyFalse(testCase, ...
        audit.IsMonotonic);

    verifyEqual(testCase, ...
        audit.ViolationCount, ...
        1);

    verifyEqual(testCase, ...
        audit.Violations.LowerFeasibleConfigId, ...
        "m25p_a50p");

    verifyEqual(testCase, ...
        audit.Violations.HigherInfeasibleConfigId, ...
        "m50p_a75p");

    verifyEqual(testCase, ...
        audit.Violations.MuscleIncrease, ...
        25);

    verifyEqual(testCase, ...
        audit.Violations.ActuatorIncrease, ...
        25);
end


function testIncomparablePointsDoNotViolateMonotonicity(testCase)

    T = ...
