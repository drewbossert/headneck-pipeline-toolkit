function testMultipleViolationsAreReportedDeterministically(testCase)

    T = ...
        localSummaryTable( ...
            [
                "m50p_a75p"
                "m25p_a50p"
                "m50p_a50p"
                "m75p_a75p"
            ], ...
            [50; 25; 50; 75], ...
            [75; 50; 50; 75], ...
            [true; true; true; true], ...
            [false; true; true; false]);

    audit = ...
        soopt.auditFeasibilityMonotonicity(T);

    verifyFalse(testCase, ...
        audit.IsMonotonic);

    verifyEqual(testCase, ...
        audit.ViolationCount, ...
        4);

    verifyEqual(testCase, ...
        audit.Violations.LowerFeasibleConfigId, ...
        [
            "m25p_a50p"
            "m25p_a50p"
            "m50p_a50p"
            "m50p_a50p"
        ]);

    verifyEqual(testCase, ...
        audit.Violations.HigherInfeasibleConfigId, ...
        [
            "m50p_a75p"
            "m75p_a75p"
            "m50p_a75p"
            "m75p_a75p"
        ]);
end


function testSingleFeasibleConfigurationIsMonotonic(testCase)

    T = ...
        localSummaryTable( ...
            "m50p_a75p", ...
            50, ...
            75, ...
            true, ...
            true);

    audit = ...
        soopt.auditFeasibilityMonotonicity(T);

    verifyTrue(testCase, ...
        audit.IsMonotonic);

    verifyEqual(testCase, ...
        audit.ViolationCount, ...
        0);
end


function testEmptyTableIsSupported(testCase)

    T = ...
        localSummaryTable( ...
            strings(0,1), ...
            zeros(0,1), ...
            zeros(0,1), ...
            false(0,1), ...
            false(0,1));

    audit = ...
        soopt.auditFeasibilityMonotonicity(T);

    verifyTrue(testCase, ...
        audit.IsMonotonic);

    verifyEqual(testCase, ...
        audit.AssessedConfigurations, ...
        0);

    verifyEqual(testCase, ...
        height(audit.Violations), ...
        0);
end


function testDuplicateConfigIdRejected(testCase)

    T = ...
        localSummaryTable( ...
            [
                "m50p_a75p"
                "m50p_a75p"
            ], ...
            [50; 50], ...
            [75; 75], ...
            [true; true], ...
            [true; false]);

    verifyError(testCase, ...
        @() soopt.auditFeasibilityMonotonicity(T), ...
        "StrengthMonotonicity:DuplicateConfigId");
end


function T = localSummaryTable( ...
        configId, musclePercent, actuatorPercent, ...
        assessmentComplete, isFeasible)

    ConfigId = ...
        string(configId(:));

    MusclePercent = ...
        double(musclePercent(:));

    ActuatorPercent = ...
        double(actuatorPercent(:));

    AssessmentComplete = ...
        logical(assessmentComplete(:));

    IsFeasible = ...
        logical(isFeasible(:));

    T = ...
        table( ...
            ConfigId, ...
            MusclePercent, ...
            ActuatorPercent, ...
            AssessmentComplete, ...
            IsFeasible);
end
