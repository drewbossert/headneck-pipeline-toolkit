%% run_static_optimization_analysis.m
% Study-level Static Optimization QC and optional pooled analysis wrapper.
%
% USER-FACING FINAL PIPELINE STAGE
%
% This script is intentionally located at the repository root rather than
% under examples/. It discovers completed Static Optimization results from
% projectCfg.outputRoot and operates on the results that actually exist.
%
% Workflow:
%   1. Search recursively for *StaticOptimization_force.sto files.
%   2. Build and write an auditable discovery manifest.
%   3. Generate per-trial QC plots for every complete detected result.
%   4. Prompt the user whether to perform pooled/condition-level analysis
%      on the detected QC-complete result set.
%
% IMPORTANT:
%   Pooled analysis assumes the detected results belong to the same
%   scientific batch/model configuration. The script reports the inferred
%   BatchRoot values and warns before combining results, but folder layout
%   alone cannot prove that all scientific settings were identical.
%
% Per-trial QC outputs:
%   <trial>/04_static_optimization/qc/plots/
%
% Study-level outputs:
%   <outputRoot>/static_optimization_analysis/
%
% The existing event-based normalization and 20-80% statistical ROI are
% retained. Project-wide analysis settings come from:
%
%   projectCfg.analysis.staticOptimization

clear;
clc;
dbstop if error

%% SECTION 0 — PROJECT AND ANALYSIS CONFIGURATION

scriptFile = ...
    string(mfilename("fullpath"));

assert(strlength(scriptFile) > 0, ...
    "SOAnalysis:ScriptLocationUnknown", ...
    "MATLAB could not resolve the running script location.");

projectRoot = ...
    string(fileparts(scriptFile));

assert(isfile(fullfile( ...
        projectRoot, ...
        "load_project_config.m")), ...
    "SOAnalysis:RepositoryRootMismatch", ...
    "run_static_optimization_analysis.m must be stored at the " + ...
    "repository root beside load_project_config.m.");

addpath(projectRoot);

projectCfg = ...
    load_project_config();

assert(isfield(projectCfg, "analysis") && ...
    isfield( ...
        projectCfg.analysis, ...
        "staticOptimization"), ...
    "SOAnalysis:AnalysisConfigMissing", ...
    "projectCfg.analysis.staticOptimization is required.");

analysisCfg = ...
    projectCfg.analysis.staticOptimization;

plotCfg = struct;

plotCfg.excludedTrials = ...
    analysisCfg.excludedTrials;

plotCfg.normalizedBreaks = ...
    analysisCfg.normalizedBreaksPercent;

plotCfg.pointsPerPhase = ...
    analysisCfg.pointsPerPhase;

plotCfg.statisticsWindowPercent = ...
    analysisCfg.statisticsWindowPercent;

plotCfg.flexionGroupName = ...
    analysisCfg.flexionGroupName;

plotCfg.extensionGroupName = ...
    analysisCfg.extensionGroupName;

plotCfg.expectedFlexorCount = ...
    analysisCfg.expectedFlexorCount;

plotCfg.expectedExtensorCount = ...
    analysisCfg.expectedExtensorCount;

plotCfg.topReserveCount = ...
    analysisCfg.topReserveCount;

plotCfg.conditionLegendOrderDeg = ...
    analysisCfg.conditionLegendOrderDeg;

analysisDirectory = ...
    string(fullfile( ...
        projectCfg.outputRoot, ...
        "static_optimization_analysis"));

if ~isfolder(analysisDirectory)
    mkdir(analysisDirectory);
end

%% SECTION 1 — DISCOVER EXISTING STATIC OPTIMIZATION RESULTS

discovery = ...
    pipeline.discoverStaticOptimizationResults( ...
        projectCfg, ...
        "ExcludedTrials", ...
            plotCfg.excludedTrials);

assert(~isempty(discovery), ...
    "SOAnalysis:NoForceResultsFound", ...
    "No Static Optimization force result files were found under:\n%s", ...
    projectCfg.outputRoot);

manifestFile = ...
    string(fullfile( ...
        analysisDirectory, ...
        "detected_static_optimization_results.csv"));

writetable( ...
    discovery, ...
    manifestFile);

fprintf( ...
    "\nDetected %d Static Optimization result location(s).\n", ...
    height(discovery));

fprintf( ...
    "Discovery manifest:\n%s\n", ...
    manifestFile);

disp(discovery(:, [ ...
    "ConditionDeg"
    "TrialNumber"
    "TrialStem"
    "BatchRoot"
    "ForceFileCount"
    "ActivationFileCount"
    "ReadyForQc"
    "ExcludedByConfig"
    "Status"
]));

eligibleMask = ...
    discovery.ReadyForQc & ...
    ~discovery.ExcludedByConfig;

eligible = ...
    discovery(eligibleMask, :);

assert(~isempty(eligible), ...
    "SOAnalysis:NoQcEligibleTrials", ...
    "Force results were detected, but none have the complete companion " + ...
    "artifacts required for per-trial QC.");

incomplete = ...
    discovery(~discovery.ReadyForQc, :);

if ~isempty(incomplete)

    warning( ...
        "SOAnalysis:IncompleteDetectedResults", ...
        "%d detected result location(s) are incomplete or ambiguous " + ...
        "and will not be processed. Review the discovery manifest.", ...
        height(incomplete));
end

if any(discovery.ExcludedByConfig)

    fprintf( ...
        "%d detected trial(s) are excluded by the configured " + ...
        "analysis exclusion list.\n", ...
        nnz(discovery.ExcludedByConfig));
end

%% SECTION 2 — GENERATE PER-TRIAL QC FOR ALL ELIGIBLE RESULTS

allNormalized = table;
allStatsWindowNormalized = table;
allMetrics = table;
allReserveAudit = table;
allMuscleAudit = table;

processedTrials = strings(0,1);
processedBatchRoots = strings(0,1);

for iTrial = 1:height(eligible)

    conditionDeg = ...
        eligible.ConditionDeg(iTrial);

    trialNumber = ...
        eligible.TrialNumber(iTrial);

    trialName = ...
        eligible.TrialStem(iTrial);

    trialRoot = ...
        eligible.TrialRoot(iTrial);

    resultsDirectory = ...
        eligible.ResultsDirectory(iTrial);

    qcDirectory = ...
        eligible.QcDirectory(iTrial);

    plotDirectory = ...
        eligible.PlotDirectory(iTrial);

    modelFile = ...
        eligible.ModelFile(iTrial);

    eventSummaryFile = ...
        eligible.EventSummaryFile(iTrial);

    forceFile = ...
        eligible.ForceFile(iTrial);

    activationFile = ...
        eligible.ActivationFile(iTrial);

    if ~isfolder(qcDirectory)
        mkdir(qcDirectory);
    end

    if ~isfolder(plotDirectory)
        mkdir(plotDirectory);
    end

%% Load detected contact events

eventSummary = readtable(eventSummaryFile);

requiredEventColumns = [ ...
    "LiftOffTime"
    "RecontactTime"
];

assert(all(ismember( ...
    requiredEventColumns, ...
    string(eventSummary.Properties.VariableNames))), ...
    "SOPlotting:EventColumnsMissing", ...
    "Event summary for %s must contain " + ...
    "LiftOffTime and RecontactTime.", ...
    trialName);

assert(height(eventSummary) == 1, ...
    "SOPlotting:UnexpectedEventRows", ...
    "Expected one event-summary row for %s.", ...
    trialName);

eventTimes = [ ...
    eventSummary.LiftOffTime, ...
    eventSummary.RecontactTime];

fprintf("\nAnalyzing %s\n", trialName);

%% Read SO outputs

forceSto = opensimio.readSto(forceFile);
activationSto = opensimio.readSto(activationFile);

forceLabels = reshape( ...
    string(forceSto.Labels), 1, []);

activationLabels = reshape( ...
    string(activationSto.Labels), 1, []);

forceTimeColumn = ...
    localFindTimeColumn(forceLabels);

activationTimeColumn = ...
    localFindTimeColumn(activationLabels);

forceTime = ...
    forceSto.Data(:, forceTimeColumn);

activationTime = ...
    activationSto.Data(:, activationTimeColumn);

assert(all(diff(forceTime) > 0), ...
    "SOPlotting:NonmonotonicForceTime", ...
    "Force time is not strictly increasing for %s.", ...
    trialName);

assert(all(diff(activationTime) > 0), ...
    "SOPlotting:NonmonotonicActivationTime", ...
    "Activation time is not strictly increasing for %s.", ...
    trialName);

rawForceBreaks = [ ...
    forceTime(1), ...
    eventTimes(1), ...
    eventTimes(2), ...
    forceTime(end)];

rawActivationBreaks = [ ...
    activationTime(1), ...
    eventTimes(1), ...
    eventTimes(2), ...
    activationTime(end)];

localValidateBreaks( ...
    rawForceBreaks, trialName);

localValidateBreaks( ...
    rawActivationBreaks, trialName);

%% Read model muscle names

import org.opensim.modeling.*

model = Model(char(modelFile));
model.finalizeConnections();

muscleSet = model.getMuscles();
numMuscles = muscleSet.getSize();

modelMuscleNames = strings(numMuscles,1);

for iMuscle = 0:(numMuscles-1)
    modelMuscleNames(iMuscle+1) = ...
        string(char( ...
            muscleSet.get(iMuscle).getName()));
end

%% Verify SO muscle columns against Model C

missingForceMuscles = setdiff( ...
    modelMuscleNames, ...
    forceLabels, ...
    "stable");

missingActivationMuscles = setdiff( ...
    modelMuscleNames, ...
    activationLabels, ...
    "stable");

assert(isempty(missingForceMuscles), ...
    "SOPlotting:MissingForceMuscles", ...
    "Force STO is missing model muscles for %s: %s", ...
    trialName, ...
    strjoin(missingForceMuscles, ", "));

assert(isempty(missingActivationMuscles), ...
    "SOPlotting:MissingActivationMuscles", ...
    "Activation STO is missing model muscles for %s: %s", ...
    trialName, ...
    strjoin(missingActivationMuscles, ", "));

%% Resolve authoritative flexion / extension ObjectGroups

flexionGroup = ...
    modelprep.getBilateralMuscleGroupMembers( ...
        modelFile, ...
        plotCfg.flexionGroupName, ...
        "RequireBilateral", ...
            true, ...
        "ExpectedResolvedCount", ...
            plotCfg.expectedFlexorCount);

extensionGroup = ...
    modelprep.getBilateralMuscleGroupMembers( ...
        modelFile, ...
        plotCfg.extensionGroupName, ...
        "RequireBilateral", ...
            true, ...
        "ExpectedResolvedCount", ...
            plotCfg.expectedExtensorCount);

flexorNames = ...
    flexionGroup.ResolvedMembers;

extensorNames = ...
    extensionGroup.ResolvedMembers;

overlapMuscles = intersect( ...
    flexorNames, ...
    extensorNames, ...
    "stable");

assert(isempty(overlapMuscles), ...
    "SOPlotting:FunctionalGroupOverlap", ...
    "One or more muscles occur in both flexion and extension " + ...
    "ObjectGroups for %s: %s", ...
    trialName, ...
    strjoin(overlapMuscles, ", "));

excludedMuscleNames = setdiff( ...
    modelMuscleNames, ...
    [flexorNames; extensorNames], ...
    "stable");

fprintf("  Flexion group:  %d muscles\n", ...
    numel(flexorNames));

fprintf("  Extension group: %d muscles\n", ...
    numel(extensorNames));

fprintf("  Excluded/other:  %d muscles\n", ...
    numel(excludedMuscleNames));

% Only explicit flexion/extension group members contribute to these
% sums. Hyoid-associated muscles, digastrics, and other unrelated
% muscles remain model muscles but are excluded from both groups.
flexorColumns = ...
    localFindColumns( ...
        forceLabels, ...
        flexorNames);

extensorColumns = ...
    localFindColumns( ...
        forceLabels, ...
        extensorNames);

flexorForce = sum( ...
    forceSto.Data(:, flexorColumns), ...
    2, ...
    "omitnan");

extensorForce = sum( ...
    forceSto.Data(:, extensorColumns), ...
    2, ...
    "omitnan");

netForce = ...
    flexorForce - extensorForce;

%% Identify non-muscle / reserve activation columns

activationNonTimeMask = ...
    true(size(activationLabels));

activationNonTimeMask( ...
    activationTimeColumn) = false;

reserveMask = ...
    activationNonTimeMask & ...
    ~ismember( ...
        activationLabels, ...
        modelMuscleNames);

reserveLabels = ...
    activationLabels(reserveMask);

reserveData = ...
    activationSto.Data(:, reserveMask);

assert(~isempty(reserveLabels), ...
    "SOPlotting:NoReserveActivations", ...
    "No non-muscle activation columns were found for %s. " + ...
    "Inspect the activation STO labels.", ...
    trialName);

maxAbsReserveByTime = ...
    max(abs(reserveData), [], 2);

rmsReserveByTime = ...
    sqrt(mean( ...
        reserveData.^2, ...
        2, ...
        "omitnan"));

peakAbsByReserve = ...
    max(abs(reserveData), [], 1);

[sortedPeakReserve, reserveOrder] = ...
    sort(peakAbsByReserve, "descend");

sortedReserveLabels = ...
    reserveLabels(reserveOrder);

reserveAudit = table( ...
    repmat(trialName, numel(reserveLabels),1), ...
    repmat(conditionDeg, numel(reserveLabels),1), ...
    repmat(trialNumber, numel(reserveLabels),1), ...
    sortedReserveLabels(:), ...
    sortedPeakReserve(:), ...
    'VariableNames', { ...
        'trial', ...
        'condition_deg', ...
        'trial_num', ...
        'reserve_label', ...
        'peak_absolute_activation'});

allReserveAudit = [ ...
    allReserveAudit
    reserveAudit]; %#ok<AGROW>

%% Muscle-group audit table

muscleGroupLabels = ...
    repmat("Excluded/other", numMuscles,1);

muscleGroupLabels( ...
    ismember(modelMuscleNames, flexorNames)) = ...
    "Flexor";

muscleGroupLabels( ...
    ismember(modelMuscleNames, extensorNames)) = ...
    "Extensor";

muscleAudit = table( ...
    repmat(trialName, numMuscles,1), ...
    repmat(conditionDeg, numMuscles,1), ...
    modelMuscleNames, ...
    muscleGroupLabels, ...
    'VariableNames', { ...
        'trial', ...
        'condition_deg', ...
        'muscle_name', ...
        'group'});

allMuscleAudit = [ ...
    allMuscleAudit
    muscleAudit]; %#ok<AGROW>

% Per-trial source-to-bilateral expansion audit. This makes it
% explicit which left-side muscle was inferred from each group
% member stored in the .osim file.
groupExpansionAudit = [ ...
    addvars( ...
        flexionGroup.Audit, ...
        repmat("Flexor", ...
            height(flexionGroup.Audit),1), ...
        'Before', 1, ...
        'NewVariableNames', "FunctionalGroup")
    addvars( ...
        extensionGroup.Audit, ...
        repmat("Extensor", ...
            height(extensionGroup.Audit),1), ...
        'Before', 1, ...
        'NewVariableNames', "FunctionalGroup")
];

writetable( ...
    groupExpansionAudit, ...
    fullfile( ...
        qcDirectory, ...
        "muscle_group_bilateral_expansion_audit.csv"));

%% Piecewise time normalization

normPercent = ...
    localMakePiecewisePercentGrid( ...
        plotCfg.normalizedBreaks, ...
        plotCfg.pointsPerPhase);

flexorNorm = ...
    localPiecewiseTimeNormalize( ...
        forceTime, ...
        flexorForce, ...
        rawForceBreaks, ...
        plotCfg.normalizedBreaks, ...
        normPercent);

extensorNorm = ...
    localPiecewiseTimeNormalize( ...
        forceTime, ...
        extensorForce, ...
        rawForceBreaks, ...
        plotCfg.normalizedBreaks, ...
        normPercent);

maxReserveNorm = ...
    localPiecewiseTimeNormalize( ...
        activationTime, ...
        maxAbsReserveByTime, ...
        rawActivationBreaks, ...
        plotCfg.normalizedBreaks, ...
        normPercent);

rmsReserveNorm = ...
    localPiecewiseTimeNormalize( ...
        activationTime, ...
        rmsReserveByTime, ...
        rawActivationBreaks, ...
        plotCfg.normalizedBreaks, ...
        normPercent);

normalizedTrial = table;
normalizedTrial.trial = ...
    repmat(trialName, numel(normPercent),1);
normalizedTrial.condition_deg = ...
    repmat(conditionDeg, numel(normPercent),1);
normalizedTrial.trial_num = ...
    repmat(trialNumber, numel(normPercent),1);
normalizedTrial.norm_percent = ...
    normPercent(:);

normalizedTrial.flexor_force_N = ...
    flexorNorm(:);

normalizedTrial.extensor_force_N = ...
    extensorNorm(:);

normalizedTrial.net_flexor_minus_extensor_N = ...
    flexorNorm(:) - extensorNorm(:);

normalizedTrial.max_abs_reserve_activation = ...
    maxReserveNorm(:);

normalizedTrial.rms_reserve_activation = ...
    rmsReserveNorm(:);

allNormalized = [ ...
    allNormalized
    normalizedTrial]; %#ok<AGROW>

%% Statistical ROI and trial metrics
%
% The complete normalized waveform remains in allNormalized for
% plotting/QC. Statistical reporting uses ONLY the configured
% normalized ROI (default 20-80%), corresponding to lift-off
% through re-contact.

np = normalizedTrial.norm_percent;

statsStartPercent = ...
    plotCfg.statisticsWindowPercent(1);

statsEndPercent = ...
    plotCfg.statisticsWindowPercent(2);

assert( ...
    statsStartPercent >= min(plotCfg.normalizedBreaks) && ...
    statsEndPercent <= max(plotCfg.normalizedBreaks) && ...
    statsEndPercent > statsStartPercent, ...
    "SOPlotting:InvalidStatisticsWindow", ...
    "Statistics window must be ordered and inside normalized range.");

idxStats = ...
    np >= statsStartPercent & ...
    np <= statsEndPercent;

assert(any(idxStats), ...
    "SOPlotting:EmptyStatisticsWindow", ...
    "Statistics ROI contains no normalized samples for %s.", ...
    trialName);

statsWindowTrial = ...
    normalizedTrial(idxStats, :);

allStatsWindowNormalized = [ ...
    allStatsWindowNormalized
    statsWindowTrial]; %#ok<AGROW>

metrics = table;
metrics.trial = trialName;
metrics.condition_deg = conditionDeg;
metrics.trial_num = trialNumber;

metrics.statistics_window_start_percent = ...
    statsStartPercent;

metrics.statistics_window_end_percent = ...
    statsEndPercent;

metrics.lift_off_time_s = ...
    eventTimes(1);

metrics.recontact_time_s = ...
    eventTimes(2);

metrics.off_support_duration_s = ...
    eventTimes(2) - eventTimes(1);

% -------------------------------------------------------------
% Muscle-force metrics: STATISTICS ROI ONLY
% -------------------------------------------------------------

[metrics.peak_flexor_N, peakFlexorIndex] = ...
    max( ...
        normalizedTrial.flexor_force_N(idxStats), ...
        [], ...
        "omitnan");

[metrics.peak_extensor_N, peakExtensorIndex] = ...
    max( ...
        normalizedTrial.extensor_force_N(idxStats), ...
        [], ...
        "omitnan");

statsNormPercent = ...
    normalizedTrial.norm_percent(idxStats);

metrics.peak_flexor_norm_percent = ...
    statsNormPercent(peakFlexorIndex);

metrics.peak_extensor_norm_percent = ...
    statsNormPercent(peakExtensorIndex);

metrics.mean_flexor_N = ...
    mean( ...
        normalizedTrial.flexor_force_N(idxStats), ...
        "omitnan");

metrics.mean_extensor_N = ...
    mean( ...
        normalizedTrial.extensor_force_N(idxStats), ...
        "omitnan");

metrics.mean_net_flexor_minus_extensor_N = ...
    mean( ...
        normalizedTrial. ...
        net_flexor_minus_extensor_N(idxStats), ...
        "omitnan");

metrics.peak_net_flexor_minus_extensor_N = ...
    max( ...
        normalizedTrial. ...
        net_flexor_minus_extensor_N(idxStats), ...
        [], ...
        "omitnan");

% -------------------------------------------------------------
% Reserve metrics: STATISTICS ROI ONLY
% -------------------------------------------------------------

metrics.peak_abs_reserve_activation = ...
    max( ...
        normalizedTrial. ...
        max_abs_reserve_activation(idxStats), ...
        [], ...
        "omitnan");

metrics.mean_max_abs_reserve_activation = ...
    mean( ...
        normalizedTrial. ...
        max_abs_reserve_activation(idxStats), ...
        "omitnan");

metrics.mean_rms_reserve_activation = ...
    mean( ...
        normalizedTrial. ...
        rms_reserve_activation(idxStats), ...
        "omitnan");

allMetrics = [ ...
    allMetrics
    metrics]; %#ok<AGROW>

%% Per-trial plot A — raw summed muscle forces

rawForceFile = string(fullfile( ...
    plotDirectory, ...
    "raw_force_diagnostics.png"));

localPlotRawForces( ...
    forceTime, ...
    flexorForce, ...
    extensorForce, ...
    netForce, ...
    rawForceBreaks, ...
    trialName, ...
    rawForceFile);

%% Per-trial plot B — reserve actuator activations

reservePlotFile = string(fullfile( ...
    plotDirectory, ...
    "reserve_activation_diagnostics.png"));

localPlotReserveActivations( ...
    activationTime, ...
    reserveData, ...
    reserveLabels, ...
    sortedReserveLabels, ...
    rawActivationBreaks, ...
    trialName, ...
    plotCfg.topReserveCount, ...
    metrics.peak_abs_reserve_activation, ...
    reservePlotFile);

%% Per-trial plot C — normalized forces

normalizedPlotFile = string(fullfile( ...
    plotDirectory, ...
    "normalized_force_diagnostics.png"));

localPlotNormalizedTrial( ...
    normalizedTrial, ...
    trialName, ...
    normalizedPlotFile);

fprintf("  Peak flexor force (%.0f-%.0f%% ROI): %.3f N\n", ...
    plotCfg.statisticsWindowPercent(1), ...
    plotCfg.statisticsWindowPercent(2), ...
    metrics.peak_flexor_N);

fprintf("  Peak extensor force (%.0f-%.0f%% ROI): %.3f N\n", ...
    plotCfg.statisticsWindowPercent(1), ...
    plotCfg.statisticsWindowPercent(2), ...
    metrics.peak_extensor_N);

fprintf("  Peak |reserve activation| (%.0f-%.0f%% ROI): %.6f\n", ...
    plotCfg.statisticsWindowPercent(1), ...
    plotCfg.statisticsWindowPercent(2), ...
    metrics.peak_abs_reserve_activation);

processedTrials(end+1,1) = trialName; %#ok<SAGROW>

    processedBatchRoots(end+1,1) = ...
        eligible.BatchRoot(iTrial); %#ok<SAGROW>
end

%% SECTION 3 — REQUIRE AT LEAST ONE QC-COMPLETE TRIAL

assert(~isempty(allNormalized), ...
    "SOAnalysis:NoTrialsProcessed", ...
    "No detected Static Optimization trials completed per-trial QC.");

fprintf( ...
    "\nPer-trial QC completed for %d trial(s):\n", ...
    numel(processedTrials));

disp(processedTrials);

uniqueBatchRoots = ...
    unique( ...
        processedBatchRoots, ...
        "stable");

fprintf( ...
    "\nDetected source batch root(s):\n");

disp(uniqueBatchRoots);

%% SECTION 4 — OPTIONAL POOLED / CONDITION-LEVEL ANALYSIS

fprintf( ...
    "\nOPTIONAL POOLED STATIC OPTIMIZATION ANALYSIS\n");

fprintf( ...
    "Per-trial QC plots have already been generated for all detected " + ...
    "eligible trials.\n");

fprintf( ...
    "\nWARNING:\n" + ...
    "Pooled statistics and condition-level plots assume that all detected " + ...
    "results belong to the same scientific batch and were generated with " + ...
    "compatible model, force-capacity, and analysis settings.\n");

if numel(uniqueBatchRoots) > 1

    warning( ...
        "SOAnalysis:MultipleBatchRootsDetected", ...
        "Detected QC-complete results span %d different BatchRoot values. " + ...
        "Review the manifest carefully before pooling these results.", ...
        numel(uniqueBatchRoots));
end

fprintf( ...
    "\n  [1] Perform pooled/condition-level analysis on these %d trial(s)\n", ...
    numel(processedTrials));

fprintf( ...
    "  [2] Finish after per-trial QC only\n");

analysisChoice = ...
    localPromptForChoice( ...
        "Selection [1/2]: ", ...
        ["1","2"]);

if analysisChoice == "2"

    fprintf( ...
        "\nPer-trial Static Optimization QC complete. " + ...
        "Pooled analysis was not requested.\n");

    return;
end

if numel(uniqueBatchRoots) > 1

    fprintf( ...
        "\nMULTIPLE BATCH ROOTS WERE DETECTED.\n");

    fprintf( ...
        "  [1] I have reviewed the manifest and want to continue anyway\n");

    fprintf( ...
        "  [2] Cancel pooled analysis\n");

    mixedBatchChoice = ...
        localPromptForChoice( ...
            "Selection [1/2]: ", ...
            ["1","2"]);

    if mixedBatchChoice == "2"

        fprintf( ...
            "\nPooled analysis cancelled. Per-trial QC outputs remain available.\n");

        return;
    end
end

