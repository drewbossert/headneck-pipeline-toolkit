%% SECTION 6 — CONDITION-LEVEL SUMMARY STATISTICS

% Every variable summarized here was calculated exclusively from the
% configured statistical ROI. Support-phase values do not contribute.

summaryVariables = [
    "peak_flexor_N"
    "peak_extensor_N"
    "mean_flexor_N"
    "mean_extensor_N"
    "mean_net_flexor_minus_extensor_N"
    "peak_net_flexor_minus_extensor_N"
    "peak_abs_reserve_activation"
    "mean_max_abs_reserve_activation"
    "mean_rms_reserve_activation"
];

conditionSummary = ...
    groupsummary( ...
        allMetrics, ...
        "condition_deg", ...
        ["mean","std"], ...
        summaryVariables);

