function choice = localPromptForChoice(promptText, validChoices)
%LOCALPROMPTFORCHOICE Wait for a valid command-line selection.

    validChoices = ...
        string(validChoices(:));

    while true

        rawChoice = ...
            input( ...
                char(promptText), ...
                "s");

        choice = ...
            strtrim(string(rawChoice));

        if any(choice == validChoices)
            return;
        end

        fprintf( ...
            "Invalid selection. Enter one of: %s\n", ...
            strjoin(validChoices, ", "));
    end
end



function index = localFindTimeColumn(labels)

    index = find(strcmpi(labels, "time"));

    assert(numel(index) == 1, ...
        "SOPlotting:TimeLookupFailed", ...
        "Could not uniquely identify the time column.");
end


function columns = localFindColumns(labels, requestedNames)

    columns = zeros(numel(requestedNames),1);

    for iName = 1:numel(requestedNames)

        match = find( ...
            labels == requestedNames(iName));

        assert(numel(match) == 1, ...
            "SOPlotting:ColumnLookupFailed", ...
            "Could not uniquely locate '%s'.", ...
            requestedNames(iName));

        columns(iName) = match;
    end
end


function localValidateBreaks(breaks, trialName)

    assert(all(isfinite(breaks)), ...
        "SOPlotting:NonfiniteEvents", ...
        "Nonfinite event time found for %s.", ...
        trialName);

    assert(all(diff(breaks) > 0), ...
        "SOPlotting:InvalidEventOrder", ...
        "Event times are not strictly increasing for %s.", ...
        trialName);
end


function grid = localMakePiecewisePercentGrid( ...
        normBreaks, pointsPerPhase)

    assert(numel(pointsPerPhase) == ...
        numel(normBreaks)-1, ...
        "SOPlotting:NormalizationDefinitionMismatch", ...
        "pointsPerPhase must have one fewer element " + ...
        "than normBreaks.");

    grid = [];

    for iPhase = 1:numel(pointsPerPhase)

        thisGrid = linspace( ...
            normBreaks(iPhase), ...
            normBreaks(iPhase+1), ...
            pointsPerPhase(iPhase)+1);

        if iPhase > 1
            thisGrid = thisGrid(2:end);
        end

        grid = [grid, thisGrid]; %#ok<AGROW>
    end

    grid = grid(:);
end


function yNorm = localPiecewiseTimeNormalize( ...
        time, y, rawBreaks, normBreaks, normPercent)

    yNorm = nan(size(normPercent));

    for iPhase = 1:(numel(rawBreaks)-1)

        rawStart = rawBreaks(iPhase);
        rawEnd = rawBreaks(iPhase+1);

        normStart = normBreaks(iPhase);
        normEnd = normBreaks(iPhase+1);

        idxNorm = ...
            normPercent >= normStart & ...
            normPercent <= normEnd;

        if iPhase > 1
            idxNorm = ...
                normPercent > normStart & ...
                normPercent <= normEnd;
        end

        phaseFraction = ...
            (normPercent(idxNorm) - normStart) ./ ...
            (normEnd - normStart);

        queryTime = ...
            rawStart + ...
            phaseFraction .* ...
            (rawEnd - rawStart);

        yNorm(idxNorm) = interp1( ...
            time, ...
            y, ...
            queryTime, ...
            "linear");
    end
end


