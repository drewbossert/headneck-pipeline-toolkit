%% SECTION 4B — OPTIONALLY APPLY SAVED FORCE-CAPACITY CONFIGURATION
%
% This is the preferred force-configuration hook for the current pipeline:
%   - IK/Body Kinematics do not depend on muscle/actuator capacities;
%   - Model C is the model ultimately consumed by Static Optimization;
%   - applying here avoids repeatedly editing Model A and Model B.
%
% Recommended pipeline behavior:
%   projectCfg.forceCapacity.applyMode = "target"
%
% "target" is idempotent. Re-running this section writes the same configured
% values. "scale" multiplies the CURRENT target-model values and therefore
% should only be used on a freshly regenerated Model C.

forceCapacityConfigResult = ...
    modelprep.applyConfiguredForceCapacitiesIfEnabled( ...
        paths.modelCFile, ...
        projectCfg, ...
        "StageName", ...
            "Model C", ...
        "AuditFile", ...
            paths.modelCForceConfigAuditCsv);

if forceCapacityConfigResult.Enabled

    assert(forceCapacityConfigResult.Applied, ...
        "ModelCPipeline:ForceConfigNotApplied", ...
        "Force-capacity configuration is enabled but was not applied " + ...
        "to Model C.");

    assert(forceCapacityConfigResult.VerificationPassed, ...
        "ModelCPipeline:ForceConfigVerificationFailed", ...
        "Applied Model C force-capacity configuration failed verification.");

    fprintf("\nForce-capacity configuration applied to Model C.\n");
    fprintf("Config:\n%s\n", ...
        forceCapacityConfigResult.ConfigFile);
    fprintf("Apply mode: %s\n", ...
        forceCapacityConfigResult.ApplyMode);
    fprintf("Audit:\n%s\n", ...
        forceCapacityConfigResult.AuditFile);

    if strcmpi( ...
            string(forceCapacityConfigResult.ApplyMode), ...
            "scale")

        warning( ...
            "ModelCPipeline:ScaleModeNonIdempotent", ...
            "Force-capacity config was applied in SCALE mode. " + ...
            "Do not rerun Section 4B on this same Model C unless " + ...
             "you intend to compound the scaling. Rebuild Model C first.");
    end

else

    fprintf( ...
        "\nForce-capacity configuration is disabled. " + ...
        "Model C ForceSet values were left unchanged.\n");
end


