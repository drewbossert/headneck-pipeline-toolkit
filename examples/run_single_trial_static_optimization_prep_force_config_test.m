%% SECTION 7 — RESAMPLE SKULL COM TO HSF TARGET RATE

hsfParameters = ...
    hsf.defaultParameters();

targetRateHz = ...
    double(hsfParameters.TargetRateHz);

interpolationMethod = ...
    string(hsfParameters.InterpolationMethod);

% Existing HSF helper. resampleCom uses name-value options, so the
% interpolation method must be supplied explicitly as a parameter value.
resampledCom = ...
    hsf.resampleCom( ...
        rawCom, ...
        targetRateHz, ...
        "InterpolationMethod", ...
        interpolationMethod);

resampledComTable = ...
    localNormalizeComToTable( ...
        resampledCom);

localValidateComTable( ...
    resampledComTable, ...
    "resampled skull CoM");

dt = diff(resampledComTable.time);

expectedDt = 1 / targetRateHz;

assert(max(abs(dt - expectedDt)) < 1e-9, ...
    "ModelCPipeline:ResampledRateMismatch", ...
    "Resampled CoM spacing does not match TargetRateHz=%g. " + ...
    "Maximum |dt - 1/Fs| = %.9g s.", ...
    targetRateHz, ...
    max(abs(dt - expectedDt)));

writetable( ...
    resampledComTable, ...
    paths.resampledComCsv);

rawSummary = ...
    localSummarizeCom( ...
        rawComTable, ...
        "raw");

resampledSummary = ...
    localSummarizeCom( ...
        resampledComTable, ...
        "resampled");

comSummary = [ ...
    rawSummary
    resampledSummary
];

writetable( ...
    comSummary, ...
    paths.comSummaryCsv);

fprintf("\nSkull CoM QC summary:\n");
disp(comSummary);

fprintf( ...
    "Resampled skull CoM written:\n%s\n", ...
    paths.resampledComCsv);

