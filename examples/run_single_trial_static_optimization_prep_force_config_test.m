    "ModelCPipeline:HsfMotionMissing", ...
    "HSF MOT was not found:\n%s", ...
    paths.hsfMotionFile);

assert(strlength(paths.externalLoadsTemplate) > 0 && ...
       isfile(paths.externalLoadsTemplate), ...
