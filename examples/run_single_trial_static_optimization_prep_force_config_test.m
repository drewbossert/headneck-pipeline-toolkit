    "ModelCPipeline:HsfValidationFailed", ...
    "Generated HSF failed validation.");

writetable( ...
    hsfResult.Summary, ...
    paths.hsfSummaryCsv);

envelopeTable = table( ...
    hsfResult.Motion.Time(:), ...
    hsfResult.SupportEnvelope(:), ...
