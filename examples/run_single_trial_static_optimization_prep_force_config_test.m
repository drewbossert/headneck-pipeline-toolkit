%% LOCAL FUNCTIONS

function comTable = localNormalizeComToTable(comInput)
%LOCALNORMALIZECOMTOTABLE Normalize common HSF CoM output schemas.

    if istable(comInput)

        names = string( ...
            comInput.Properties.VariableNames);

        timeName = localFindVariable( ...
            names, ...
            "time");

        xName = localFindVariable( ...
            names, ...
            ["x","posx","comx","centerofmassx"]);

        yName = localFindVariable( ...
            names, ...
            ["y","posy","comy","centerofmassy"]);

        zName = localFindVariable( ...
            names, ...
            ["z","posz","comz","centerofmassz"]);

        comTable = table( ...
            double(comInput.(timeName)), ...
            double(comInput.(xName)), ...
            double(comInput.(yName)), ...
            double(comInput.(zName)), ...
            'VariableNames', { ...
                'time','x','y','z'});

        return;
    end

    if isstruct(comInput)

        if all(isfield(comInput, ...
                {'Time','X','Y','Z'}))

            comTable = table( ...
                double(comInput.Time(:)), ...
                double(comInput.X(:)), ...
                double(comInput.Y(:)), ...
                double(comInput.Z(:)), ...
                'VariableNames', { ...
                    'time','x','y','z'});

            return;
        end

        if all(isfield(comInput, ...
                {'time','x','y','z'}))

            comTable = table( ...
                double(comInput.time(:)), ...
                double(comInput.x(:)), ...
                double(comInput.y(:)), ...
                double(comInput.z(:)), ...
                'VariableNames', { ...
                    'time','x','y','z'});

            return;
        end

        if isfield(comInput, "Time") && ...
                isfield(comInput, "Data")

            data = ...
                double(comInput.Data);

            assert(size(data,2) >= 4, ...
                "ModelCPipeline:ComStructDataShape", ...
                "CoM struct contains Time/Data but Data has fewer " + ...
                "than four columns.");

            if size(data,1) == numel(comInput.Time)

                % If Data includes time, discard it when it duplicates Time.
                if max(abs(data(:,1) - ...
                        double(comInput.Time(:)))) < 1e-10

                    xyz = data(:,2:4);
                else
                    xyz = data(:,1:3);
                end

                comTable = table( ...
                    double(comInput.Time(:)), ...
                    xyz(:,1), ...
                    xyz(:,2), ...
                    xyz(:,3), ...
                    'VariableNames', { ...
                        'time','x','y','z'});

                return;
            end
        end
    end

    error( ...
        "ModelCPipeline:UnsupportedComSchema", ...
        "Could not normalize the output returned by the HSF CoM " + ...
        "helper. Inspect class(rawCom) / fieldnames(rawCom) and add " + ...
        "that schema to localNormalizeComToTable.");
end


function name = localFindVariable(variableNames, candidates)

    normalizedNames = lower( ...
        regexprep(variableNames, "[^a-zA-Z0-9]", ""));

    normalizedCandidates = lower( ...
        regexprep(candidates, "[^a-zA-Z0-9]", ""));

    match = false(size(variableNames));

    for candidate = normalizedCandidates
        match = match | ...
            normalizedNames == candidate;
    end

    assert(nnz(match) == 1, ...
        "ModelCPipeline:ComVariableLookupFailed", ...
        "Could not uniquely identify a CoM variable. " + ...
        "Available variables: %s", ...
        strjoin(variableNames, ", "));

    name = ...
        variableNames(match);
end


function localValidateComTable(comTable, label)

    assert(height(comTable) >= 2, ...
        "ModelCPipeline:ComTooShort", ...
        "%s contains fewer than two samples.", ...
        label);

    values = [ ...
        comTable.time, ...
        comTable.x, ...
        comTable.y, ...
        comTable.z];

    assert(all(isfinite(values), "all"), ...
        "ModelCPipeline:ComNonfinite", ...
        "%s contains nonfinite values.", ...
        label);

    assert(all(diff(comTable.time) > 0), ...
        "ModelCPipeline:ComTimeNotIncreasing", ...
        "%s time is not strictly increasing.", ...
        label);
end


function summary = localSummarizeCom(comTable, stage)

    dt = diff(comTable.time);

    if isempty(dt)
        estimatedRateHz = NaN;
    else
        estimatedRateHz = ...
            1 / median(dt);
    end

    summary = table( ...
        string(stage), ...
        height(comTable), ...
        comTable.time(1), ...
        comTable.time(end), ...
        estimatedRateHz, ...
        min(comTable.x), ...
        max(comTable.x), ...
        min(comTable.y), ...
        max(comTable.y), ...
        min(comTable.z), ...
        max(comTable.z), ...
        'VariableNames', { ...
            'Stage', ...
            'NumSamples', ...
            'StartTime', ...
            'EndTime', ...
            'EstimatedRateHz', ...
            'MinimumX', ...
            'MaximumX', ...
            'MinimumY', ...
            'MaximumY', ...
            'MinimumZ', ...
            'MaximumZ'});
end