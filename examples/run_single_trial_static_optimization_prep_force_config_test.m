        'time', ...
        'support_envelope'});

writetable( ...
    envelopeTable, ...
    paths.hsfEnvelopeCsv);

fprintf("\nHSF summary:\n");
disp(hsfResult.Summary);

fprintf("HSF MOT written:\n%s\n", ...
    paths.hsfMotionFile);

fprintf("HSF envelope QC written:\n%s\n", ...
    paths.hsfEnvelopeCsv);

