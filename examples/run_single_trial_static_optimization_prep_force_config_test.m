%% SECTION 9 — GENERATE REAL HEAD-SUPPORT-FORCE MOT


assert(exist("resampledCom", "var") == 1, ...
    "ModelCPipeline:ResampledComMissing", ...
    "Run Section 7 before generating the HSF.");

assert(~isempty(trialCfg.liftOffWindow), ...
    "ModelCPipeline:LiftOffWindowMissing", ...
    "No detected lift-off/re-contact window is available. " + ...
    "Run Section 8 before generating the HSF.");

assert( ...
    isnumeric(trialCfg.liftOffWindow) && ...
    numel(trialCfg.liftOffWindow) == 2 && ...
    all(isfinite(trialCfg.liftOffWindow)) && ...
    trialCfg.liftOffWindow(2) > trialCfg.liftOffWindow(1), ...
    "ModelCPipeline:InvalidLiftOffWindow", ...
    "Detected liftOffWindow must be [lift_off recontact] in seconds.");

% Extract gndroll directly from the validated final IK. It is explicitly
% locked in Model B, so its range should be numerically negligible.
finalLabels = ...
    reshape(string(finalIkMotion.Labels), 1, []);

gndrollColumn = find( ...
    finalLabels == "gndroll");

assert(numel(gndrollColumn) == 1, ...
    "ModelCPipeline:GndrollLookupFailed", ...
    "Could not uniquely locate gndroll in the final IK motion.");

gndrollValuesDeg = ...
    finalIkMotion.Data(:, gndrollColumn);

assert(all(isfinite(gndrollValuesDeg)), ...
    "ModelCPipeline:NonfiniteGndroll", ...
    "Final IK gndroll contains nonfinite values.");

gndrollRangeDeg = ...
    max(gndrollValuesDeg) - ...
    min(gndrollValuesDeg);

assert(gndrollRangeDeg <= ...
        auditQc.rotationRangeToleranceDeg, ...
    "ModelCPipeline:GndrollNotConstant", ...
    "gndroll varies by %.9g deg in final IK; expected it to be locked " + ...
    "within %.9g deg.", ...
    gndrollRangeDeg, ...
    auditQc.rotationRangeToleranceDeg);

gndrollDeg = ...
    median(gndrollValuesDeg);

fprintf("\nHSF generation inputs:\n");
fprintf("  Condition:        %.6g deg\n", trialCfg.conditionDeg);
fprintf("  gndroll:          %.9g deg\n", gndrollDeg);
fprintf("  Lift-off:         %.9g s\n", trialCfg.liftOffWindow(1));
fprintf("  Re-contact:       %.9g s\n", trialCfg.liftOffWindow(2));
fprintf("  CoM samples:      %d\n", numel(resampledCom.Time));
fprintf("  CoM target rate:  %.6g Hz\n", hsfParameters.TargetRateHz);

hsfResult = ...
    hsf.generateFromResampledCom( ...
        resampledCom, ...
        trialCfg.conditionDeg, ...
        gndrollDeg, ...
        trialCfg.liftOffWindow, ...
        paths.hsfMotionFile, ...
        "Parameters", ...
            hsfParameters, ...
        "Overwrite", ...
            trialCfg.overwriteExisting, ...
        "MotionName", ...
            trialStem + "_head_support_force");

