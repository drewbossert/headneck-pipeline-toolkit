%% run_single_trial_static_optimization_prep.m
% Single-trial Model C + Body Kinematics + skull CoM preparation.
%
% CURRENT VALIDATION TARGET:
%   condition 0 deg, trial 1
%
% This script deliberately stops after a validated, resampled skull CoM
% trajectory. HSF force synthesis and ExternalLoads generation should be
% connected only after this real CoM stage is confirmed.
%
% INPUT FROM MODEL B
%   - Model B .osim
%   - validated final IK .mot
%   - Model B checkpoint
%
% OUTPUT
%   03_static_optimization_prep/
%       <trial>_modelC_static_optimization.osim
%       body_kinematics/
%           <trial>_body_kinematics_setup.xml
%           results/
%           qc/
%               skull_com_raw.csv
%               skull_com_resampled.csv
%               skull_com_summary.csv
%       qc/
%           modelC_coordinate_configuration.csv
%           modelC_constraint_configuration.csv
%           model_c_checkpoint.mat

