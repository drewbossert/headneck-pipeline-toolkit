%% run_single_trial_model_b.m
% Single-trial validation driver: lock extraction, Model B, and final IK.
%
% Run this script one section at a time. It resumes from the Phase A
% initialization-IK checkpoint and intentionally stops after final-IK QC.
%
% REQUIRED TOOLKIT COMPONENTS
%   load_project_config.m
%   +opensimio
%   +modelprep
%   +opensimrun
%
% REQUIRED PHASE A OUTPUT
%   initialization_ik_checkpoint.mat
%
% MODEL B CONFIGURATION
%   - Coordinate-coupler constraints enabled
%   - Root coordinates locked
%   - Independent roll/yaw coordinates locked
%   - Independent sagittal coordinates unlocked
%   - All auxiliary coordinates remain unlocked, dependent, and constrained
%   - Dependent r1/r2 coordinates are expected to remain constant because
%     their independent out-of-plane drivers are locked
%   - Dependent r3 coordinates remain free to vary through their sagittal
%     coupler relationships
%
% FINAL-IK QC GOALS
%   - Verify the ten requested Model B locks
%   - Verify dependent-coordinate model state
%   - Describe dependent out-of-plane behavior without treating it as a
%     generic stability test
%   - Quantify independent and dependent sagittal motion for Model C design

%% SECTION 0 — LOAD PROJECT AND TRIAL CONFIGURATION

clear;
clc;
dbstop if error

% Live Editor evaluates sections through a temporary helper file, so prefer
% the active Editor document when locating the repository.
activeFile = string(matlab.desktop.editor.getActiveFilename);

if strlength(activeFile) > 0 && isfile(activeFile)
    scriptFile = activeFile;
else
    scriptFile = string(mfilename("fullpath"));
end

assert(strlength(scriptFile) > 0 && isfile(scriptFile), ...
    "ModelBPipeline:ScriptLocationUnknown", ...
    "Save and open this script in the MATLAB Editor before running its sections.");

examplesDirectory = string(fileparts(scriptFile));
projectRoot = string(fileparts(examplesDirectory));

assert(isfolder(fullfile(projectRoot, "+modelprep")), ...
    "ModelBPipeline:ProjectRootNotFound", ...
    "The inferred project root does not contain +modelprep:\n%s\n\nSave this script under the repository's examples folder.", ...
    projectRoot);

addpath(projectRoot);

projectCfg = load_project_config();

assert(string(projectCfg.projectRoot) == projectRoot, ...
    "ModelBPipeline:ProjectRootMismatch", ...
    "Script-inferred project root:\n%s\n\nConfiguration project root:\n%s", ...
    projectRoot, projectCfg.projectRoot);

trialCfg = struct;

% Trial identity.
trialCfg.conditionDeg = 45;
trialCfg.trialNumber = 1;

% Initial support interval used to assess filtering and extract the
% Model B lock values. The 0.10 s offset avoids the beginning-of-record
% endpoint while preserving the intended 0.25 s supported-pose duration.
trialCfg.lockWindow = [0.10, 0.15];

% Leave empty to use the Phase A checkpoint marker-file path.
% Set an explicit local path when the checkpoint was created elsewhere.
trialCfg.markerFile = "";

% Execution controls.
trialCfg.overwriteExisting = projectCfg.overwriteExisting;
trialCfg.executeFinalIk = true;

fprintf( ...
    "Machine: %s\nCondition: %g deg\nTrial: %d\n", ...
    projectCfg.machineName, ...
    trialCfg.conditionDeg, ...
    trialCfg.trialNumber);


%% SECTION 1 — RESOLVE PHASE A AND MODEL B PATHS

conditionFolderName = sprintf( ...
    "%02ddeg", round(trialCfg.conditionDeg));

trialFolderName = sprintf( ...
    "trial%02d", trialCfg.trialNumber);

trialRoot = string(fullfile( ...
    projectCfg.outputRoot, ...
    conditionFolderName, ...
    trialFolderName));

phaseADirectory = string(fullfile( ...
    trialRoot, ...
    "01_initialization_ik"));

phaseAQcDirectory = string(fullfile( ...
    phaseADirectory, ...
    "qc"));

phaseBDirectory = string(fullfile( ...
    trialRoot, ...
    "02_locked_final_ik"));

phaseBQcDirectory = string(fullfile( ...
    phaseBDirectory, ...
    "qc"));

if ~isfolder(phaseBDirectory)
    mkdir(phaseBDirectory);
end

if ~isfolder(phaseBQcDirectory)
    mkdir(phaseBQcDirectory);
end

paths = struct;

paths.trialRoot = trialRoot;
paths.phaseADirectory = phaseADirectory;
paths.phaseAQcDirectory = phaseAQcDirectory;
paths.phaseBDirectory = phaseBDirectory;
paths.phaseBQcDirectory = phaseBQcDirectory;

paths.initializationCheckpointFile = string(fullfile( ...
    phaseAQcDirectory, ...
    "initialization_ik_checkpoint.mat"));

paths.modelAFile = string(fullfile( ...
    phaseADirectory, ...
    sprintf("%s_%s_modelA_initialization.osim", ...
    conditionFolderName, trialFolderName)));

paths.initialIkMotionFile = string(fullfile( ...
    phaseADirectory, ...
    sprintf("%s_%s_initialization_ik.mot", ...
    conditionFolderName, trialFolderName)));

