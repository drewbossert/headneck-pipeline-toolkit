paths.dependentSagittalSummaryCsv = string(fullfile( ...
    phaseBQcDirectory, ...
    "final_ik_dependent_sagittal_summary.csv"));

paths.sagittalSummaryCsv = string(fullfile( ...
    phaseBQcDirectory, ...
    "final_ik_sagittal_summary.csv"));

