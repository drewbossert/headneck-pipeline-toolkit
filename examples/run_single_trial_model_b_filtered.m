    phaseBQcDirectory, ...
    "final_ik_sagittal_trajectories.csv"));

paths.sagittalRelativeTrajectoriesCsv = string(fullfile( ...
    phaseBQcDirectory, ...
    "final_ik_sagittal_relative_trajectories.csv"));

