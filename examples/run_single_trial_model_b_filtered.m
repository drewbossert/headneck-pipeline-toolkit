    paths.initializationCheckpointFile, ...
    "checkpoint");

assert(isfield(loadedCheckpoint, "checkpoint"), ...
    "ModelBPipeline:CheckpointVariableMissing", ...
    "The MAT file does not contain a variable named checkpoint.");

checkpointA = loadedCheckpoint.checkpoint;

requiredCheckpointFields = [ ...
    "Configuration"
    "Paths"
    "ModelAValidation"
    "IkMotionSummary"
    "IkRunResult"
];

for fieldName = requiredCheckpointFields.'
    assert(isfield(checkpointA, fieldName), ...
        "ModelBPipeline:CheckpointFieldMissing", ...
        "Phase A checkpoint is missing field: %s", ...
        fieldName);
end

assert(logical(checkpointA.ModelAValidation.Passed), ...
    "ModelBPipeline:ModelAWasInvalid", ...
    "The Phase A checkpoint reports that Model A failed validation.");

assert(logical(checkpointA.IkRunResult.RunSucceeded), ...
    "ModelBPipeline:InitializationIkFailed", ...
    "The Phase A checkpoint reports that initialization IK failed.");

assert( ...
    checkpointA.Configuration.conditionDeg == ...
        trialCfg.conditionDeg, ...
    "ModelBPipeline:ConditionMismatch", ...
    ["Configured condition is %g deg, but the checkpoint is for " ...
     "%g deg."], ...
    trialCfg.conditionDeg, ...
    checkpointA.Configuration.conditionDeg);

assert( ...
    checkpointA.Configuration.trialNumber == ...
        trialCfg.trialNumber, ...
    "ModelBPipeline:TrialMismatch", ...
    "Configured trial is %d, but the checkpoint is for trial %d.", ...
    trialCfg.trialNumber, ...
    checkpointA.Configuration.trialNumber);

assert(isfile(paths.modelAFile), ...
    "ModelBPipeline:ModelAMissing", ...
    "Model A was not found:\n%s", ...
    paths.modelAFile);

assert(isfile(paths.initialIkMotionFile), ...
    "ModelBPipeline:InitializationMotionMissing", ...
    "Initialization IK motion was not found:\n%s", ...
    paths.initialIkMotionFile);

assert(isfile(projectCfg.kinematicBaseModel), ...
    "ModelBPipeline:BaseModelMissing", ...
    "Configured kinematic base model was not found:\n%s", ...
    projectCfg.kinematicBaseModel);

assert(isfile(projectCfg.initializationIkTemplate), ...
    "ModelBPipeline:IkTemplateMissing", ...
    "Configured IK template was not found:\n%s", ...
    projectCfg.initializationIkTemplate);

if strlength(string(trialCfg.markerFile)) == 0
    markerFile = string(checkpointA.Configuration.markerFile);
else
    markerFile = string(trialCfg.markerFile);
end

assert(isfile(markerFile), ...
    "ModelBPipeline:MarkerFileMissing", ...
    "Marker file was not found:\n%s\n\nIf the checkpoint came from another computer, set trialCfg.markerFile to the local marker-file path.", ...
    markerFile);

trialTimeRange = [ ...
    checkpointA.IkMotionSummary.StartTime, ...
    checkpointA.IkMotionSummary.EndTime];

assert( ...
    trialCfg.lockWindow(1) >= trialTimeRange(1) && ...
    trialCfg.lockWindow(2) <= trialTimeRange(2) && ...
    trialCfg.lockWindow(2) > trialCfg.lockWindow(1), ...
    "ModelBPipeline:InvalidLockWindow", ...
    "Lock window [%.9g, %.9g] must lie within the trial range [%.9g, %.9g].", ...
    trialCfg.lockWindow(1), ...
    trialCfg.lockWindow(2), ...
    trialTimeRange(1), ...
    trialTimeRange(2));

fprintf( ...
    "Phase A checkpoint validated. Trial range: %.5f to %.5f s.\n", ...
    trialTimeRange(1), trialTimeRange(2));


%% SECTION 3 — LOAD SHARED QC SETTINGS

assert(isfield(projectCfg, "qc"), ...
    "ModelBPipeline:QcConfigMissing", ...
    "projectCfg.qc is not defined in project_defaults.m.");

assert(isfield(projectCfg.qc, "lockExtraction"), ...
    "ModelBPipeline:LockExtractionConfigMissing", ...
    "projectCfg.qc.lockExtraction is not defined. Add the Model B QC block to config/project_defaults.m.");

assert(isfield(projectCfg.qc, "lockExtractionFilter"), ...
    "ModelBPipeline:LockFilterConfigMissing", ...
    "projectCfg.qc.lockExtractionFilter is not defined. Add the Model B filtering block to config/project_defaults.m.");

assert(isfield(projectCfg.qc, "lockAudit"), ...
    "ModelBPipeline:LockAuditConfigMissing", ...
    "projectCfg.qc.lockAudit is not defined. Add the locked-coordinate audit block to config/project_defaults.m.");

extractionQc = projectCfg.qc.lockExtraction;
filterQc = projectCfg.qc.lockExtractionFilter;
auditQc = projectCfg.qc.lockAudit;

requiredExtractionFields = [ ...
    "statistic"
    "rotationToleranceDeg"
    "translationToleranceM"
    "otherToleranceSI"
    "minimumSamples"
    "requireStable"
];

for fieldName = requiredExtractionFields.'
    assert(isfield(extractionQc, fieldName), ...
        "ModelBPipeline:LockExtractionFieldMissing", ...
        "Missing projectCfg.qc.lockExtraction.%s", ...
        fieldName);
end

requiredFilterFields = [ ...
    "enabled"
    "filterCoordinates"
    "prototypeOrder"
    "selectedCutoffHz"
];

for fieldName = requiredFilterFields.'
    assert(isfield(filterQc, fieldName), ...
        "ModelBPipeline:LockFilterFieldMissing", ...
        "Missing projectCfg.qc.lockExtractionFilter.%s", ...
        fieldName);
end

assert(islogical(filterQc.enabled) && isscalar(filterQc.enabled), ...
    "ModelBPipeline:InvalidLockFilterEnabled", ...
    "projectCfg.qc.lockExtractionFilter.enabled must be a logical scalar.");

if filterQc.enabled
    assert(~isempty(filterQc.filterCoordinates), ...
        "ModelBPipeline:NoFilterCoordinates", ...
        "Filtering is enabled but filterCoordinates is empty.");

    assert(isnumeric(filterQc.prototypeOrder) && ...
        isscalar(filterQc.prototypeOrder) && ...
        isfinite(filterQc.prototypeOrder) && ...
        filterQc.prototypeOrder >= 1 && ...
        mod(filterQc.prototypeOrder, 1) == 0, ...
        "ModelBPipeline:InvalidFilterOrder", ...
        "prototypeOrder must be a positive integer.");

    assert(isnumeric(filterQc.selectedCutoffHz) && ...
        isscalar(filterQc.selectedCutoffHz) && ...
        isfinite(filterQc.selectedCutoffHz) && ...
        filterQc.selectedCutoffHz > 0, ...
        "ModelBPipeline:InvalidFilterCutoff", ...
        "selectedCutoffHz must be a positive finite scalar when filtering is enabled.");
end

requiredAuditFields = [ ...
    "statistic"
    "rotationRangeToleranceDeg"
    "translationRangeToleranceM"
    "otherRangeToleranceSI"
    "rotationMatchToleranceDeg"
    "translationMatchToleranceM"
    "otherMatchToleranceSI"
    "minimumSamples"
    "requirePass"
];

for fieldName = requiredAuditFields.'
    assert(isfield(auditQc, fieldName), ...
        "ModelBPipeline:LockAuditFieldMissing", ...
        "Missing projectCfg.qc.lockAudit.%s", ...
        fieldName);
end

disp(extractionQc);
disp(filterQc);
disp(auditQc);


%% SECTION 4 — FILTER INITIALIZATION IK FOR LOCK EXTRACTION

groups = modelprep.coordinateGroups();

requiredGroupFields = [ ...
    "Root"
    "IndependentOutOfPlane"
    "DependentOutOfPlane"
    "IndependentSagittal"
    "DependentSagittal"
    "Sagittal"
    "AllDependent"
    "FinalIkLocked"
];

for iGroup = 1:numel(requiredGroupFields)
    groupName = requiredGroupFields(iGroup);

    assert(isfield(groups, groupName), ...
        "ModelBPipeline:CoordinateGroupMissing", ...
        "modelprep.coordinateGroups is missing groups.%s.", ...
        groupName);
end

% By default, use the raw Phase A initialization IK. When filtering is
% enabled, this variable is redirected to the filtered Phase B artifact.
lockExtractionMotionFile = paths.initialIkMotionFile;

lockFilterResult = struct;
lockFilterResult.Enabled = logical(filterQc.enabled);

if filterQc.enabled

    filterCoordinates = ...
        reshape(string(filterQc.filterCoordinates), 1, []);

    assert(all(ismember(filterCoordinates, groups.FinalIkLocked)), ...
        "ModelBPipeline:UnexpectedFilterCoordinate", ...
        "All lock-extraction filter coordinates must belong to groups.FinalIkLocked. Requested: %s", ...
        strjoin(filterCoordinates, ", "));

    if isfile(paths.filteredInitialIkMotionFile) && ...
            ~trialCfg.overwriteExisting
        error("ModelBPipeline:OutputExists", ...
            "Filtered initialization IK already exists:\n%s\n\nSet trialCfg.overwriteExisting=true to regenerate it.", ...
            paths.filteredInitialIkMotionFile);
    end

    filterResult = ...
        modelprep.filterCoordinateMotion( ...
        paths.initialIkMotionFile, ...
        filterCoordinates, ...
        "CutoffHz", filterQc.selectedCutoffHz, ...
        "PrototypeOrder", filterQc.prototypeOrder, ...
        "AuditWindow", trialCfg.lockWindow);

    opensimio.writeOpenSimTable( ...
        paths.filteredInitialIkMotionFile, ...
        filterResult.Motion);

    writetable( ...
        filterResult.Audit, ...
        paths.lockFilterAuditCsv);

    lockExtractionMotionFile = ...
        paths.filteredInitialIkMotionFile;

    lockFilterResult.Enabled = true;
    lockFilterResult.SourceMotionFile = ...
        paths.initialIkMotionFile;
    lockFilterResult.FilteredMotionFile = ...
        paths.filteredInitialIkMotionFile;
    lockFilterResult.AuditFile = ...
        paths.lockFilterAuditCsv;
    lockFilterResult.FilteredCoordinates = ...
        filterResult.FilteredCoordinates;
    lockFilterResult.SampleRateHz = ...
        filterResult.SampleRateHz;
    lockFilterResult.CutoffHz = ...
        filterResult.CutoffHz;
    lockFilterResult.PrototypeOrder = ...
        filterResult.PrototypeOrder;
    lockFilterResult.EffectiveZeroPhaseOrder = ...
        filterResult.EffectiveZeroPhaseOrder;
    lockFilterResult.AuditWindow = ...
        filterResult.AuditWindow;
    lockFilterResult.NumAuditSamples = ...
        filterResult.NumAuditSamples;
    lockFilterResult.Audit = ...
        filterResult.Audit;

    fprintf( ...
        "Filtered initialization IK for Model B lock extraction.\nCoordinates: %s\nCutoff: %.3f Hz\nPrototype order: %d (effective zero-phase order %d)\nFiltered motion:\n%s\n", ...
        strjoin(filterCoordinates, ", "), ...
        filterResult.CutoffHz, ...
        filterResult.PrototypeOrder, ...
        filterResult.EffectiveZeroPhaseOrder, ...
        paths.filteredInitialIkMotionFile);

    disp(filterResult.Audit);

else

    lockFilterResult.SourceMotionFile = ...
        paths.initialIkMotionFile;
    lockFilterResult.FilteredMotionFile = "";
    lockFilterResult.AuditFile = "";
    lockFilterResult.FilteredCoordinates = strings(1, 0);

    fprintf( ...
        "Lock-extraction filtering is disabled. Using the raw Phase A initialization IK.\n");

end

fprintf( ...
    "Motion used for Model B lock extraction:\n%s\n", ...
    lockExtractionMotionFile);

% CHECKPOINT:
% Review modelB_lock_filter_audit.csv before continuing. Confirm that the
% filtered yaw coordinates have acceptable range/standard deviation within
% trialCfg.lockWindow and that the median shifts remain reasonable.


%% SECTION 5 — EXTRACT TRIAL-SPECIFIC MODEL B LOCK VALUES

lockValues = modelprep.extractStableCoordinateValues( ...
    lockExtractionMotionFile, ...
    paths.modelAFile, ...
    groups.FinalIkLocked, ...
    trialCfg.lockWindow, ...
    "Method", extractionQc.statistic, ...
    "RotationToleranceDeg", ...
        extractionQc.rotationToleranceDeg, ...
    "TranslationToleranceM", ...
        extractionQc.translationToleranceM, ...
    "OtherTolerance", ...
        extractionQc.otherToleranceSI, ...
    "RequireStable", false, ...
    "MinimumSamples", ...
        extractionQc.minimumSamples);

writetable(lockValues, paths.lockValuesCsv);

disp(lockValues);

if any(~lockValues.IsStable)
    unstableCoordinates = ...
        lockValues.Coordinate(~lockValues.IsStable);

    fprintf( ...
        "\nCoordinates exceeding the extraction tolerance:\n%s\n", ...
        strjoin(unstableCoordinates, ", "));
end

if extractionQc.requireStable
    assert(all(lockValues.IsStable), ...
        "ModelBPipeline:UnstableLockValues", ...
        "One or more coordinates are unstable in the selected window. Review modelB_lock_values.csv and modelB_lock_filter_audit.csv.");
end

fprintf( ...
    "Lock values extracted from [%.5f, %.5f] s and saved:\n%s\n", ...
    trialCfg.lockWindow(1), ...
    trialCfg.lockWindow(2), ...
    paths.lockValuesCsv);

% CHECKPOINT:
% Review modelB_lock_values.csv before constructing Model B. The six root
% coordinates and four independent roll/yaw coordinates should represent
% the supported initial pose.


%% SECTION 6 — BUILD MODEL B

if isfile(paths.modelBFile) && ~trialCfg.overwriteExisting
    error("ModelBPipeline:OutputExists", ...
        "Model B already exists:\n%s", ...
        paths.modelBFile);
end

modelBResult = modelprep.buildLockedIkModel( ...
    projectCfg.kinematicBaseModel, ...
    lockValues, ...
    paths.modelBFile, ...
    "CoordinateNames", groups.FinalIkLocked, ...
    "RequireStable", extractionQc.requireStable);

writetable( ...
    modelBResult.Inspection.Coordinates, ...
    paths.modelBCoordinateConfigurationCsv);

writetable( ...
    modelBResult.Inspection.Constraints, ...
    paths.modelBConstraintConfigurationCsv);

fprintf("Model B written:\n%s\n", paths.modelBFile);


%% SECTION 7 — VALIDATE MODEL B CONFIGURATION

modelBInspection = modelprep.inspectModel(paths.modelBFile);

allCoordinateNames = ...
    modelBInspection.Coordinates.Coordinate;

expectedUnlocked = setdiff( ...
    allCoordinateNames, ...
    groups.FinalIkLocked, ...
    "stable");

modelBValidation = modelprep.validateModelConfiguration( ...
    paths.modelBFile, ...
    "ExpectedLocked", groups.FinalIkLocked, ...
    "ExpectedUnlocked", expectedUnlocked, ...
    "ExpectedConstraintsEnforced", true, ...
    "ThrowOnFailure", true);

assert(modelBValidation.Passed, ...
    "ModelBPipeline:ModelBValidationFailed", ...
    "Model B configuration validation failed.");

% Inspect all auxiliary coordinates that are dependent on couplers.
dependentRows = ismember( ...
    modelBInspection.Coordinates.Coordinate, ...
    groups.AllDependent);

dependentCoordinateState = ...
    modelBInspection.Coordinates(dependentRows, { ...
        'Coordinate'
        'DefaultLocked'
        'StateLocked'
        'StateDependent'
        'StateConstrained'
    });

writetable( ...
    dependentCoordinateState, ...
    paths.modelBDependentCoordinateStateCsv);

fprintf("\nAll dependent-coordinate Model B states:\n");
disp(dependentCoordinateState);

assert(all(~dependentCoordinateState.DefaultLocked), ...
    "ModelBPipeline:DependentCoordinateDefaultLocked", ...
    "One or more dependent auxiliary coordinates are default-locked.");

assert(all(~dependentCoordinateState.StateLocked), ...
    "ModelBPipeline:DependentCoordinateStateLocked", ...
    "One or more dependent auxiliary coordinates are state-locked.");

assert(all(dependentCoordinateState.StateDependent), ...
    "ModelBPipeline:DependentCoordinateNotDependent", ...
    "One or more expected auxiliary coordinates are not dependent.");

assert(all(dependentCoordinateState.StateConstrained), ...
    "ModelBPipeline:DependentCoordinateUnconstrained", ...
    "One or more expected auxiliary coordinates are not constrained.");

% Inspect the independent sagittal drivers separately. These should remain
% unlocked so final IK can solve the intended flexion/extension motion.
independentSagittalRows = ismember( ...
    modelBInspection.Coordinates.Coordinate, ...
    groups.IndependentSagittal);

independentSagittalState = ...
    modelBInspection.Coordinates(independentSagittalRows, { ...
        'Coordinate'
        'DefaultLocked'
        'StateLocked'
        'StateDependent'
        'StateConstrained'
    });

writetable( ...
    independentSagittalState, ...
    paths.independentSagittalStateCsv);

fprintf("\nIndependent sagittal-coordinate Model B states:\n");
disp(independentSagittalState);

assert(all(~independentSagittalState.DefaultLocked), ...
    "ModelBPipeline:IndependentSagittalDefaultLocked", ...
    "One or more independent sagittal coordinates are default-locked.");

assert(all(~independentSagittalState.StateLocked), ...
    "ModelBPipeline:IndependentSagittalStateLocked", ...
    "One or more independent sagittal coordinates are state-locked.");

assert(all(~independentSagittalState.StateDependent), ...
    "ModelBPipeline:IndependentSagittalUnexpectedlyDependent", ...
    "One or more expected independent sagittal coordinates are dependent.");

fprintf( ...
    "Model B validation passed: requested coordinates locked, all auxiliary coordinates dependent/constrained, and independent sagittal drivers unlocked.\n");


%% SECTION 8 — CREATE THE FINAL-IK SETUP

if isfile(paths.finalIkSetupFile) && ...
        ~trialCfg.overwriteExisting
