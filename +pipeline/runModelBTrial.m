function localAssertOutputsAbsent( ...
        paths, filteringEnabled, executeFinalIk, writeQc, saveCheckpoint)

    outputFiles = [
        string(paths.ModelBFile)
        string(paths.FinalIkSetupFile)
    ];

    if filteringEnabled

        outputFiles(end+1,1) = ...
            string(paths.FilteredInitialIkMotionFile);
    end

    if executeFinalIk

        outputFiles(end+1,1) = ...
            string(paths.FinalIkMotionFile);
    end

    if writeQc

        outputFiles = [
            outputFiles
            string(paths.LockValuesCsv)
            string(paths.CoordinateConfigurationCsv)
            string(paths.ConstraintConfigurationCsv)
            string(paths.DependentCoordinateStateCsv)
            string(paths.IndependentSagittalStateCsv)
        ];

        if filteringEnabled

            outputFiles(end+1,1) = ...
                string(paths.LockFilterAuditCsv);
        end

        if executeFinalIk

            outputFiles = [
                outputFiles
                string(paths.LockedCoordinateAuditCsv)
                string(paths.DependentOutOfPlaneSummaryCsv)
                string(paths.IndependentSagittalSummaryCsv)
                string(paths.DependentSagittalSummaryCsv)
                string(paths.SagittalSummaryCsv)
                string(paths.SagittalTrajectoriesCsv)
                string(paths.SagittalRelativeTrajectoriesCsv)
            ];
        end
    end

    if executeFinalIk && saveCheckpoint

        outputFiles(end+1,1) = ...
            string(paths.CheckpointFile);
    end

    existingFiles = ...
        outputFiles(isfile(outputFiles));

    if ~isempty(existingFiles)

        error( ...
            "PipelineModelB:OutputExists", ...
            "Process-2 output already exists and Overwrite=false:\n%s", ...
            strjoin(existingFiles, newline));
    end
end


