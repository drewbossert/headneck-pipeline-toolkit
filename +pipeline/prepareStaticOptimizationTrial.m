function apply = ...
        localShouldApplyForceConfig( ...
            projectCfg, stageName)

    apply = false;

    if ~isfield(projectCfg, "forceCapacity") || ...
            ~isstruct(projectCfg.forceCapacity)
        return;
    end

    cfg = ...
        projectCfg.forceCapacity;

    if ~isfield(cfg, "enabled") || ...
            ~logical(cfg.enabled)
        return;
    end

    if ~isfield(cfg, "applyStages")

        apply = true;
        return;
    end

    stages = ...
        lower(string(cfg.applyStages(:)));

    apply = ...
        any(stages == lower(string(stageName)));
end


