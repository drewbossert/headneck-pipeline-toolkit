        hsfParameters, ...
        gndrollResult, ...
        hsfResult, ...
        externalLoadsResult, ...
        staticOptimizationSetupResult, ...
        checkpointFile, ...
        true, ...
        toc(stageStart));

    if printProgress

        fprintf( ...
            "Detected lift-off: %.6f s; re-contact: %.6f s.\n", ...
            liftOffWindowSec(1), ...
            liftOffWindowSec(2));

        fprintf( ...
            "HSF skull mass: %.9g kg.\n", ...
            hsfParameters.SkullMassKg);

        fprintf( ...
            "Process 3 completed in %.3f s.\n", ...
            result.DurationSeconds);

        fprintf( ...
            "Model C:\n%s\n", ...
            paths.ModelCFile);

        fprintf( ...
            "HSF MOT:\n%s\n", ...
            paths.HeadSupportForce.MotionFile);

