function localAssertOutputsAbsent( ...
        paths, soPaths, executeBodyKinematics, ...
        writeQc, saveCheckpoint, forceConfigWillApply)

    outputFiles = [
        string(paths.ModelCFile)
    ];

    if writeQc

        outputFiles = [
            outputFiles
            string(paths.CoordinateConfigurationCsv)
            string(paths.ConstraintConfigurationCsv)
        ];

        if forceConfigWillApply

            outputFiles(end+1,1) = ...
                string(paths.ForceConfigAuditCsv);
        end
    end

    if executeBodyKinematics

        outputFiles = [
            outputFiles
            string(paths.BodyKinematics.SetupFile)
            string(paths.HeadSupportForce.MotionFile)
            string(paths.HeadSupportForce.ExternalLoadsFile)
            string(soPaths.SetupFile)
        ];

        if writeQc

            outputFiles = [
                outputFiles
                string(paths.BodyKinematics.RawComCsv)
                string(paths.BodyKinematics.ResampledComCsv)
                string(paths.BodyKinematics.ComSummaryCsv)
                string(paths.HeadSupportForce.EventDetectionSummaryCsv)
                string(paths.HeadSupportForce.EventDetectionPlot)
                string(paths.HeadSupportForce.SummaryCsv)
                string(paths.HeadSupportForce.SupportEnvelopeCsv)
            ];
        end

        if saveCheckpoint

            outputFiles(end+1,1) = ...
                string(paths.CheckpointFile);
        end
    end

    existingFiles = ...
        outputFiles(isfile(outputFiles));

    if ~isempty(existingFiles)

        error( ...
            "PipelineSOPrep:OutputExists", ...
            "Process-3 output already exists and Overwrite=false:\n%s", ...
            strjoin(existingFiles, newline));
    end
end


function comTable = localComToTable(com)

    requiredFields = [
        "Time"
        "X"
        "Y"
        "Z"
    ];

    assert(all(isfield( ...
            com, ...
            cellstr(requiredFields))), ...
        "PipelineSOPrep:InvalidComStructure", ...
        "CoM structure must contain Time, X, Y, and Z.");

    comTable = table( ...
        double(com.Time(:)), ...
        double(com.X(:)), ...
        double(com.Y(:)), ...
        double(com.Z(:)), ...
        'VariableNames', { ...
            'time', ...
            'x', ...
            'y', ...
            'z'});
end


function localValidateComTable(comTable, label)

    assert(height(comTable) >= 2, ...
        "PipelineSOPrep:ComTooShort", ...
        "%s contains fewer than two samples.", ...
        label);

    values = [
        comTable.time
        comTable.x
        comTable.y
        comTable.z
    ];

    assert(all(isfinite(values), "all"), ...
        "PipelineSOPrep:ComNonfinite", ...
        "%s contains nonfinite values.", ...
        label);

    assert(all(diff(comTable.time) > 0), ...
        "PipelineSOPrep:ComTimeNotIncreasing", ...
        "%s time is not strictly increasing.", ...
        label);
end


function summary = ...
        localSummarizeCom( ...
            comTable, stage)

    dt = ...
        diff(comTable.time);

    if isempty(dt)

        estimatedRateHz = ...
            NaN;

    else

        estimatedRateHz = ...
            1 / median(dt);
    end

    summary = table( ...
        string(stage), ...
        height(comTable), ...
        comTable.time(1), ...
        comTable.time(end), ...
        estimatedRateHz, ...
        min(comTable.x), ...
        max(comTable.x), ...
        min(comTable.y), ...
        max(comTable.y), ...
        min(comTable.z), ...
        max(comTable.z), ...
        'VariableNames', { ...
            'Stage', ...
            'NumSamples', ...
            'StartTime', ...
            'EndTime', ...
            'EstimatedRateHz', ...
            'XMin', ...
            'XMax', ...
            'YMin', ...
            'YMax', ...
            'ZMin', ...
            'ZMax'});
end


